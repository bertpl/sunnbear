"""This module builds `summary.md` and `timeline.html`, which give an overview of the sources and how they relate.

The folder's README gives the rules for the edges and the common functions; `COMMON_MIN_SOURCES` and
`COMMON_MAX_LENGTH` set the 2 limits of a common function.
"""

import json
import re
from collections import Counter
from dataclasses import dataclass
from pathlib import Path

from .data_files import FINAL_STATUSES, SUBCATEGORY_DESCRIPTIONS, UNDECIDED, RowsTableLine, Source, join_row_ids

COMMON_MIN_SOURCES = 6
COMMON_MAX_LENGTH = 14
TIMELINE_TEMPLATE = Path(__file__).with_name("timeline_template.html")


# ==================================================================================================
#  Overview
# ==================================================================================================
@dataclass(frozen=True)
class Overview:
    """An `Overview` holds the sources in time order, their status counts, their edges and the common functions."""

    sources: tuple[Source, ...]
    rows: tuple[RowsTableLine, ...]
    # edges maps (index of the earlier source, index of the later source) to the number of rows.
    edges: dict[tuple[int, int], int]
    common: tuple["CommonFunction", ...]

    def status_counts(self, source_id: str) -> dict[str, int]:
        """Return the number of rows of a source in total and per status."""
        counts = dict.fromkeys(("rows", *FINAL_STATUSES, UNDECIDED), 0)
        for row in self.rows:
            if row.source_id == source_id:
                counts["rows"] += 1
                counts[row.final_status.status] += 1
        return counts

    def summary_markdown(self) -> str:
        """Return `summary.md`: the totals, 1 table line per source, and the common functions."""
        totals = dict.fromkeys(FINAL_STATUSES, 0)
        for row in self.rows:
            totals[row.final_status.status] = totals.get(row.final_status.status, 0) + 1
        lines = [
            "# Summary of the literature test problems",
            "",
            "Generated by `python -m scripts.literature_test_problems`; the README of this folder explains the "
            "summary.",
            "",
            f"**{len(self.sources)} sources, {len(self.rows):,} rows:** "
            + ", ".join(f"{n:,} {status}" for status, n in totals.items())
            + ".",
            "",
            "| year | source | title | subcategory | rows | new | takes rows from |",
            "|---|---|---|---|---|---|---|",
        ]
        for i, source in enumerate(self.sources):
            counts = self.status_counts(source.source_id)
            taken_from = sorted(((n, a) for (a, b), n in self.edges.items() if b == i), key=lambda e: (-e[0], e[1]))
            taken_from_text = ", ".join(f"`{self.sources[a].source_id}` ({n})" for n, a in taken_from)
            lines.append(
                f"| {source.year} | `{source.source_id}` | {self._strip_markdown(source.title)} | {source.subcategory} "
                f"| {counts['rows']} | {counts['new']} | {taken_from_text} |"
            )
        lines += [
            "",
            "## Common functions",
            "",
            f"A common function is a row whose `f` has at most {COMMON_MAX_LENGTH} characters and that later rows of "
            f"at least {COMMON_MIN_SOURCES} sources name in `duplicate_of` or `derived_from`. Common functions "
            "count in the rows of each source, but not in the column *takes rows from*.",
            "",
            "| row | f | sources |",
            "|---|---|---|",
            *(f"| `{c.row_id}` | `{c.f}` | {c.n_sources} |" for c in self.common),
        ]
        return "\n".join(lines) + "\n"

    def timeline_html(self) -> str:
        """Return `timeline.html`: the template with the overview's data embedded as JSON."""
        data = {
            "sources": [
                {
                    "id": source.source_id,
                    "label": re.sub(
                        r"\s*\(\d{4}[a-z]?\)\s*$", "", self._strip_markdown(source.title).split(":")[0].strip()
                    ),
                    "title": self._strip_markdown(source.title),
                    "reference": self._strip_markdown(source.reference),
                    "year": source.year,
                    "subcategory": source.subcategory,
                    "counts": self.status_counts(source.source_id),
                    "namesEarlier": [
                        [row.key, row.final_status.status, join_row_ids(row.final_status.named_row_ids)]
                        for row in self.rows
                        if row.source_id == source.source_id and row.final_status.named_row_ids
                    ],
                }
                for source in self.sources
            ],
            "edges": [{"from": a, "to": b, "rows": n} for (a, b), n in sorted(self.edges.items())],
            "common": [{"row": c.row_id, "f": c.f, "sources": c.n_sources} for c in self.common],
            "subcategories": SUBCATEGORY_DESCRIPTIONS,
            "commonMinSources": COMMON_MIN_SOURCES,
            "commonMaxLength": COMMON_MAX_LENGTH,
        }
        template = TIMELINE_TEMPLATE.read_text(encoding="utf-8")
        # escape "</" so that no string in the data can close the page's <script> element
        return template.replace("/*DATA*/", json.dumps(data).replace("</", "<\\/"))

    # --------------------------------------------------------------------------
    #  Helpers
    # --------------------------------------------------------------------------
    @staticmethod
    def _strip_markdown(text: str) -> str:
        """Return markdown text without its backticks and asterisks, for the places that show it as plain text."""
        return re.sub(r"[`*]", "", text)

    # --------------------------------------------------------------------------
    #  Factory methods
    # --------------------------------------------------------------------------
    @classmethod
    def build(cls, sources: list[Source], rows: list[RowsTableLine]) -> "Overview":
        """Return the overview of the sources and their rows, both given in time order.

        A common function is a row whose `f` has at most `COMMON_MAX_LENGTH` characters and that later rows of at
        least `COMMON_MIN_SOURCES` sources name. An edge from an earlier to a later source counts the later source's
        rows that name a row of the earlier source; a common function adds no edge.
        """
        index_of_source = {source.source_id: i for i, source in enumerate(sources)}
        row_by_id = {row.row_id: row for row in rows}
        # sources_naming maps each row id to the sources whose rows name that row in duplicate_of or derived_from.
        sources_naming: dict[str, set[str]] = {}
        for row in rows:
            for earlier in row.final_status.named_row_ids:
                sources_naming.setdefault(earlier, set()).add(row.source_id)
        position = {row.row_id: i for i, row in enumerate(rows)}
        common = []
        for row_id in sorted(sources_naming, key=lambda r: (-len(sources_naming[r]), position.get(r, len(rows)))):
            f = row_by_id[row_id].f if row_id in row_by_id else ""
            if f and len(sources_naming[row_id]) >= COMMON_MIN_SOURCES and len(f) <= COMMON_MAX_LENGTH:
                common.append(CommonFunction(row_id, f, len(sources_naming[row_id])))
        common_ids = {c.row_id for c in common}
        edges: Counter[tuple[int, int]] = Counter()
        for row in rows:
            earlier_sources = {
                row_by_id[e].source_id for e in row.final_status.named_row_ids if e in row_by_id and e not in common_ids
            }
            for earlier_source in sorted(earlier_sources - {row.source_id}):
                edges[(index_of_source[earlier_source], index_of_source[row.source_id])] += 1
        return cls(sources=tuple(sources), rows=tuple(rows), edges=dict(edges), common=tuple(common))


# ==================================================================================================
#  CommonFunction
# ==================================================================================================
@dataclass(frozen=True)
class CommonFunction:
    """A `CommonFunction` is a row that later rows of many sources name, and that adds no edges."""

    row_id: str
    f: str
    n_sources: int
