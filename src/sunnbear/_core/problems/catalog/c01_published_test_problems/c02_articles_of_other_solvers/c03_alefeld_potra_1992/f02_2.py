import math

from sunnbear._core.problems.core import Formula, FormulaSource, FormulaTestCase, ParamRecipe

# SURVEY_FIELDS_HASH is a hash of this formula's survey fields; the tests recompute it from the
# survey, so that a test fails when the survey changes and this module is not regenerated.
SURVEY_FIELDS_HASH = "9d58c9297aa046ee"


class AlefeldPotra19922(Formula):
    """This formula comes from Alefeld, Potra (1992).

    The survey writes the source's function as ``x^2*(x^2/3 + sqrt(2)*sin(x)) - sqrt(3)/18``; the formula's interval is
    ``[0.1, 1]``.
    """

    number = (1, 2, 3, 2)
    name = "2"
    param_names = ()
    source = FormulaSource(
        reference=(
            "Alefeld, G. E., Potra, F. A. (1992). Some efficient methods for enclosing simple zeros of "
            "nonlinear equations. BIT 32(2), 334–344. https://doi.org/10.1007/bf01994885."
        ),
        location="2",
    )

    @staticmethod
    def parametrized_fun(x: float, c: float) -> float:
        """Evaluate the published function at ``x - c_scale*c``; category 1 states the rule for ``c_scale``."""
        x = x - 0.9 * c
        return x**2 * (x**2 / 3 + math.sqrt(2) * math.sin(x)) - math.sqrt(3) / 18

    def interval_bounds(self) -> tuple[float, float]:
        """Return the formula's interval."""
        return (0.1, 1.0)

    def recipes(self) -> tuple[ParamRecipe, ...]:
        """Return no recipe, since the published function has no parameters."""
        return ()

    test_cases = (
        FormulaTestCase.value(params={}, x=0.37, c=0.0, expected=-0.01996698326641826),
        FormulaTestCase.value(params={}, x=0.37, c=0.25, expected=-0.09178137984886615),
        FormulaTestCase.interval_bounds(params={}, expected=(0.1, 1.0)),
    )
