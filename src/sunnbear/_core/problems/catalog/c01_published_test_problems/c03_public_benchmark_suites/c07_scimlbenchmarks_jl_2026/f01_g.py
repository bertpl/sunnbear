"""This module holds a formula of SciMLBenchmarks.jl (2026).

The formula comes from the row with the key ``g`` in the survey of published test problems. A script generates this
module from that survey: to change the formula, change its source file in `data/literature_test_problems/sources/` and
run `uv run python -m scripts.literature_test_problems.formula_modules sciml_interval_suite`; do not edit this file.
"""

import math

from sunnbear._core.problems.core import Formula, FormulaSource, FormulaTestCase, ParamRecipe

# SURVEY_FIELDS_HASH is a hash of this formula's survey fields; the tests recompute it from the
# survey, so that a test fails when the survey changes and this module is not regenerated.
SURVEY_FIELDS_HASH = "5a771f64293b4025"


class ScimlbenchmarksJl2026G(Formula):
    """This formula comes from SciMLBenchmarks.jl (2026).

    The survey writes the source's function as ``exp(u) - 1e-15``; the formula's interval is ``[-100.0, 0.0]``.

    section "A different function"; the file gives the root as `u = - 15 * log(10)`; the solvers of
    `BracketingNonlinearSolve.jl` call it through `g(u, p) = g(u)`
    """

    number = (1, 3, 7, 1)
    name = "g"
    param_names = ()
    source = FormulaSource(
        reference=(
            'SciMLBenchmarks.jl, "Interval Rootfinding Test Suite" by Fabian Gittins (the front matter '
            "of the file), file `benchmarks/IntervalNonlinearProblem/suite.jmd` at commit "
            "`8a67931f726eeb53604926a6dd6bfc750316b4c4`, "
            "https://github.com/SciML/SciMLBenchmarks.jl/blob/8a67931f726eeb53604926a6dd6bfc750316b4c4/benchmarks/IntervalNonlinearProblem/suite.jmd,"
            ' MIT license. The file names no source for its functions; it calls them "a selection of '
            'challenging test functions from the literature".'
        ),
        location="g",
    )

    @staticmethod
    def parametrized_fun(x: float, c: float) -> float:
        """Evaluate the published function at ``x - c_scale*c``; category 1 states the rule for ``c_scale``."""
        x = x - 100.0 * c
        return math.exp(x) - 1e-15

    def interval_bounds(self) -> tuple[float, float]:
        """Return the formula's interval."""
        return (-100.0, 0.0)

    def recipes(self) -> tuple[ParamRecipe, ...]:
        """Return no recipe, since the published function has no parameters."""
        return ()

    # a case with `atol=0.0` has an expected value so small that the default `atol`
    # would accept any value near 0, 0 among them
    test_cases = (
        FormulaTestCase.value(params={}, x=-15.0, c=0.0, expected=3.059023195018258e-07),
        FormulaTestCase.value(params={}, x=-70.0, c=0.25, expected=-1e-15, atol=0.0),
        FormulaTestCase.interval_bounds(params={}, expected=(-100.0, 0.0)),
    )
