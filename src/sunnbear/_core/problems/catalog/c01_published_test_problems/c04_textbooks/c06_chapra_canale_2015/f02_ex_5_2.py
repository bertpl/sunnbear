        FormulaTestCase.value(params={"a": 0.0, "b": 5.0, "c_scale": 5.0}, x=1.5, c=0.25, expected=1.3301610129777774),
        FormulaTestCase.value(params={"a": 3.0, "b": 5.0, "c_scale": 2.0}, x=3.6, c=0.0, expected=-1.186108759898451),
