class BurdenFairesBurden201622Ex3(Formula):
    """This formula comes from Burden, Faires, Burden (2016).

    The source prints 3 functions that differ only in the values of some constants; with those constants replaced by
    parameters, the 3 functions become 1 function, ``x - k^-x``:

    - §2.2 Ex. 3; Fig. 2.5; 2.5-1(c), with ``k = 3``: ``x = 3^-x``; the formula's interval is ``[0, 1]``
    - 2.1-5(a); 2.5-8, with ``k = 2``: ``x - 2^-x``; the formula's interval is ``[0, 1]``
    - 2.2-10, with ``k = 2``: ``x = 2^-x``; the formula's interval is ``[1/3, 1]``

    The value ``1/3`` is rounded to 12 significant digits, the most that a parameter value holds.

    §2.2 Ex. 3; Fig. 2.5; 2.5-1(c): Unique fixed point on `[0, 1]`, which Theorem 2.3 cannot show, since `abs(g'(0)) =
    log(3) > 1`. 2.5-1(c) applies Aitken's method to the iteration from `p0 = 0.5`.

    2.1-5(a); 2.5-8: Bisection to `1E-5` (2.1-5); Steffensen's method to `1E-4`, compared with 2.2-10 (2.5-8). Its root
    is the fixed point of 2.2-10's `x = 2^-x`.

    2.2-10: As 2.2-9, to `1E-4`.
    """

    number = (1, 4, 7, 6)
    name = "§2.2 Ex. 3"
    param_names = ("k", "a", "b", "c_scale")
    source = FormulaSource(
        reference=(
            "Burden, R. L., Faires, J. D., Burden, A. M. (2016). Numerical Analysis, 10th edition. "
            "Cengage Learning, Boston, MA. ISBN 978-1-305-25366-7. The copyright page gives © 2016 and "
            "the print year 2014."
        ),
        location="§2.2 Ex. 3; Fig. 2.5; 2.5-1(c), 2.1-5(a); 2.5-8, 2.2-10",
    )

    @staticmethod
    def parametrized_fun(x: float, c: float, k: float, a: float, b: float, c_scale: float) -> float:
        """Evaluate the published function at ``x - c_scale*c``; category 1 states the rule for ``c_scale``."""
        x = x - c_scale * c
        return x - k**-x

    def interval_bounds(self, k: float, a: float, b: float, c_scale: float) -> tuple[float, float]:
        """Return the interval of the tuple, its parameters ``a`` and ``b``."""
        return (a, b)

