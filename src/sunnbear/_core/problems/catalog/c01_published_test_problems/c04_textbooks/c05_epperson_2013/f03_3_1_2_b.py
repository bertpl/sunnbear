"""This module holds a formula of Epperson (2013).

The formula comes from the row with the key ``3.1-2(b)`` in the survey of published test problems. A script generates
this module from that survey: to change the formula, change its source file in `data/literature_test_problems/sources/`
and run `uv run python -m scripts.literature_test_problems.formula_modules 2013_epperson`; do not edit this file.
"""

import math

from sunnbear._core.problems.core import Formula, FormulaSource, FormulaTestCase, ParamRecipe

# SURVEY_FIELDS_HASH is a hash of this formula's survey fields; the tests recompute it from the
# survey, so that a test fails when the survey changes and this module is not regenerated.
SURVEY_FIELDS_HASH = "9a7b7a832d74f23d"


class Epperson2013312B(Formula):
    """This formula comes from Epperson (2013).

    The survey writes the source's function as ``log(x) + x``; the formula's interval is ``[1/10, 1]``.

    3.1-2 asks for the root to an accuracy of 0.1 by bisection, by hand.
    """

    number = (1, 4, 5, 3)
    name = "3.1-2(b)"
    param_names = ()
    source = FormulaSource(
        reference=(
            "Epperson, J. F. (2013). An Introduction to Numerical Methods and Analysis, 2nd edition. "
            "John Wiley & Sons, Hoboken, NJ. ISBN 978-1-118-36759-9."
        ),
        location="3.1-2(b)",
    )

    @staticmethod
    def parametrized_fun(x: float, c: float) -> float:
        """Evaluate the published function at ``x - c_scale*c``; category 1 states the rule for ``c_scale``."""
        x = x - 0.9 * c
        return math.log(x) + x

    def interval_bounds(self) -> tuple[float, float]:
        """Return the formula's interval."""
        return (0.1, 1.0)

    def recipes(self) -> tuple[ParamRecipe, ...]:
        """Return no recipe, since the published function has no parameters."""
        return ()

    test_cases = (
        FormulaTestCase.value(params={}, x=0.37, c=0.0, expected=-0.6242522733438669),
        FormulaTestCase.value(params={}, x=0.37, c=0.25, expected=-1.7860215365615628),
        FormulaTestCase.interval_bounds(params={}, expected=(0.1, 1.0)),
    )
