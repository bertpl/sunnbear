"""This module holds the formula that Oliveira, Takahashi (2021) labels 1.9.

A script generates this module from the survey of published test problems: to change the formula, change its source file
in `data/literature_test_problems/sources/` and run `uv run python -m scripts.literature_test_problems.formula_modules
2021_oliveira_takahashi`; do not edit this file.
"""

import math

from sunnbear._core.functions.core import Formula, FormulaSource, FormulaTestCase, ParamRecipe

# SURVEY_FIELDS_HASH is a hash of this formula's survey fields; the tests recompute it from the
# survey, so that a test fails when the survey changes and this module is not regenerated.
SURVEY_FIELDS_HASH = "5f7d1024a652becf"


class OliveiraTakahashi202119(Formula):
    """This formula evaluates the published function at ``x - (b - a)*c``, where ``[a, b]`` is its interval.

    The survey writes the source's function as ``1/10^3 + sum(sin(pi*i^3*x/2)/(pi*i^3), i = 1..10)``; the formula's
    interval is ``[-1, 1]``.

    The article prints the divisor as `/pi i^3`, without parentheses; the formula divides by `pi*i^3`, as the authors'
    MATLAB code and sunnbear's test transcription in `tests/solvers/paper_problems/oliveira_takahashi.py` do.
    """

    number = (1, 1, 9, 8)
    name = "1.9"
    param_names = ()
    source = FormulaSource(
        reference=(
            "Oliveira, I. F. D., Takahashi, R. H. C. (2021). An enhancement of the bisection method "
            "average performance preserving minmax optimality. ACM Transactions on Mathematical "
            "Software 47(1), Article 5. https://doi.org/10.1145/3423597. The article itself is dated "
            "December 2020."
        ),
        location="1.9",
    )

    @staticmethod
    def parametrized_fun(x: float, c: float) -> float:
        """Evaluate the published function at ``x - (b - a)*c``, where ``[a, b]`` is the formula's interval."""
        x = x - 2.0 * c
        return 1 / 10**3 + (
            (math.sin(math.pi * (1) ** 3 * x / 2) / (math.pi * (1) ** 3))
            + (math.sin(math.pi * (2) ** 3 * x / 2) / (math.pi * (2) ** 3))
            + (math.sin(math.pi * (3) ** 3 * x / 2) / (math.pi * (3) ** 3))
            + (math.sin(math.pi * (4) ** 3 * x / 2) / (math.pi * (4) ** 3))
            + (math.sin(math.pi * (5) ** 3 * x / 2) / (math.pi * (5) ** 3))
            + (math.sin(math.pi * (6) ** 3 * x / 2) / (math.pi * (6) ** 3))
            + (math.sin(math.pi * (7) ** 3 * x / 2) / (math.pi * (7) ** 3))
            + (math.sin(math.pi * (8) ** 3 * x / 2) / (math.pi * (8) ** 3))
            + (math.sin(math.pi * (9) ** 3 * x / 2) / (math.pi * (9) ** 3))
            + (math.sin(math.pi * (10) ** 3 * x / 2) / (math.pi * (10) ** 3))
        )

    def interval_bounds(self) -> tuple[float, float]:
        """Return the formula's interval."""
        return (-1.0, 1.0)

    def recipes(self) -> tuple[ParamRecipe, ...]:
        """Return no recipe, since the published function has no parameters."""
        return ()

    cases = (
        FormulaTestCase.value(params={}, x=-0.4, c=0.0, expected=-0.14031870036510996),
        FormulaTestCase.value(params={}, x=-0.4, c=0.25, expected=-0.28624612512652314),
        FormulaTestCase.interval_bounds(params={}, expected=(-1.0, 1.0)),
    )
