"""This module holds a formula of Ford (1997).

The formula comes from the row with the key ``2`` in the survey of published test problems. A script generates this
module from that survey: to change the formula, change its source file in `data/literature_test_problems/sources/` and
run `uv run python -m scripts.literature_test_problems.formula_modules 1997_ford`; do not edit this file.
"""

from sunnbear._core.functions.core import Formula, FormulaSource, FormulaTestCase, ParamRecipe, ParamTable

# SURVEY_FIELDS_HASH is a hash of this formula's survey fields; the tests recompute it from the
# survey, so that a test fails when the survey changes and this module is not regenerated.
SURVEY_FIELDS_HASH = "a6aaeedd0071ca72"


class Ford19972(Formula):
    """This formula comes from Ford (1997).

    The survey writes the source's function as ``10^-8*(x - 1)*prod(x^2 + x + i, i = 1..10)``; the formula's intervals
    are `[0.9, 1.1]`; `[0.5, 1.5]`; `[-5, 10]`.

    Printed root: `x* = 1.0`. The article says Hopgood and McKee study this function.
    """

    number = (1, 1, 8, 2)
    name = "2"
    param_names = ("a", "b", "c_scale")
    source = FormulaSource(
        reference=(
            "Ford, J. A. (1997). Improved Illinois-type methods for the solution of nonlinear "
            "equations. Scientia Iranica 4(1&2), 28–34. The article has no working DOI: the journal's "
            "page, https://scientiairanica.sharif.edu/article_21758.html, lists "
            "10.24200/sci.2020.21758, which doi.org does not resolve. An earlier version is the "
            "University of Essex technical report CSM-257 (1995)."
        ),
        location="2",
    )

    @staticmethod
    def parametrized_fun(x: float, c: float, a: float, b: float, c_scale: float) -> float:
        """Evaluate the published function at ``x - c_scale*c``; category 1 states the rule for ``c_scale``."""
        x = x - c_scale * c
        return (
            10**-8
            * (x - 1)
            * (
                (x**2 + x + (1))
                * (x**2 + x + (2))
                * (x**2 + x + (3))
                * (x**2 + x + (4))
                * (x**2 + x + (5))
                * (x**2 + x + (6))
                * (x**2 + x + (7))
                * (x**2 + x + (8))
                * (x**2 + x + (9))
                * (x**2 + x + (10))
            )
        )

    def interval_bounds(self, a: float, b: float, c_scale: float) -> tuple[float, float]:
        """Return the interval of the tuple, its parameters ``a`` and ``b``."""
        return (a, b)

    def recipes(self) -> tuple[ParamRecipe, ...]:
        """Return the published parameter values."""
        return (ParamTable(names=("a", "b", "c_scale"), rows=((0.9, 1.1, 0.2), (0.5, 1.5, 1.0), (-5.0, 10.0, 15.0))),)

    cases = (
        FormulaTestCase.value(
            params={"a": 0.9, "b": 1.1, "c_scale": 0.2}, x=0.96, c=0.0, expected=-0.07905914659719734
        ),
        FormulaTestCase.value(
            params={"a": 0.9, "b": 1.1, "c_scale": 0.2}, x=0.96, c=0.25, expected=-0.1400565243092936
        ),
        FormulaTestCase.value(params={"a": 0.5, "b": 1.5, "c_scale": 1.0}, x=0.8, c=0.0, expected=-0.18486721613136733),
        FormulaTestCase.value(
            params={"a": -5.0, "b": 10.0, "c_scale": 15.0}, x=-0.5, c=0.0, expected=-0.024747659447550772
        ),
        FormulaTestCase.interval_bounds(params={"a": 0.9, "b": 1.1, "c_scale": 0.2}, expected=(0.9, 1.1)),
        FormulaTestCase.interval_bounds(params={"a": 0.5, "b": 1.5, "c_scale": 1.0}, expected=(0.5, 1.5)),
        FormulaTestCase.interval_bounds(params={"a": -5.0, "b": 10.0, "c_scale": 15.0}, expected=(-5.0, 10.0)),
    )
