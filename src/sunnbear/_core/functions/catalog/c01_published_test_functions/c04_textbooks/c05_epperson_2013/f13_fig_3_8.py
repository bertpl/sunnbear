"""This module holds a formula of Epperson (2013).

The formula comes from the row with the key ``Fig. 3.8`` in the survey of published test problems. A script generates
this module from that survey: to change the formula, change its source file in `data/literature_test_problems/sources/`
and run `uv run python -m scripts.literature_test_problems.formula_modules 2013_epperson`; do not edit this file.
"""

from sunnbear._core.functions.core import Formula, FormulaSource, FormulaTestCase, ParamRecipe

# SURVEY_FIELDS_HASH is a hash of this formula's survey fields; the tests recompute it from the
# survey, so that a test fails when the survey changes and this module is not regenerated.
SURVEY_FIELDS_HASH = "c3c4cdc6c49bb2e8"


class Epperson2013Fig38(Formula):
    """This formula evaluates the published function at ``x - (b - a)*c``, where ``[a, b]`` is its interval.

    The survey writes the source's function as ``(1/2)*x^2 - 1/2``; the formula's interval is `[0, 4]` (Fig. 3.8).

    Figure only: 2 Newton steps.
    """

    number = (1, 4, 5, 13)
    name = "Fig. 3.8"
    param_names = ()
    source = FormulaSource(
        reference=(
            "Epperson, J. F. (2013). An Introduction to Numerical Methods and Analysis, 2nd edition. "
            "John Wiley & Sons, Hoboken, NJ. ISBN 978-1-118-36759-9."
        ),
        location="Fig. 3.8",
    )

    @staticmethod
    def parametrized_fun(x: float, c: float) -> float:
        """Evaluate the published function at ``x - (b - a)*c``, where ``[a, b]`` is the formula's interval."""
        x = x - 4.0 * c
        return (1 / 2) * x**2 - 1 / 2

    def interval_bounds(self) -> tuple[float, float]:
        """Return the formula's interval."""
        return (0.0, 4.0)

    def recipes(self) -> tuple[ParamRecipe, ...]:
        """Return no recipe, since the published function has no parameters."""
        return ()

    cases = (
        FormulaTestCase.value(params={}, x=1.2, c=0.0, expected=0.21999999999999995),
        FormulaTestCase.value(params={}, x=1.2, c=0.25, expected=-0.48),
        FormulaTestCase.interval_bounds(params={}, expected=(0.0, 4.0)),
    )
