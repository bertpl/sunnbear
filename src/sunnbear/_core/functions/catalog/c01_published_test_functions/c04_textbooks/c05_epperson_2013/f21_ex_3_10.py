"""This module holds a formula of Epperson (2013).

The formula comes from the row with the key ``Ex. 3.10, 3.11, 3.14`` in the survey of published test problems. A script
generates this module from that survey: to change the formula, change its source file in
`data/literature_test_problems/sources/` and run `uv run python -m scripts.literature_test_problems.formula_modules
2013_epperson`; do not edit this file.
"""

from sunnbear._core.functions.core import Formula, FormulaSource, FormulaTestCase, ParamRecipe

# SURVEY_FIELDS_HASH is a hash of this formula's survey fields; the tests recompute it from the
# survey, so that a test fails when the survey changes and this module is not regenerated.
SURVEY_FIELDS_HASH = "b2bb95d482e16920"


class Epperson2013Ex310(Formula):
    """This formula comes from Epperson (2013).

    The survey writes the source's function as ``x^4 - x - 1``; the formula's interval is `[-2, 2]` (Fig. 3.11).

    Real roots 1.22074408460576 and -0.72449195900052, complex roots `-0.24812606280262 ± 1.03398206097597i`. Newton
    from `x0 = 1.25` and `x0 = -0.75`, then deflation (Ex. 3.10, Table 3.7); Durand–Kerner from complex starts (Ex.
    3.11, Table 3.8), and from the real starts 1, -1, 2, -2, where it fails (Ex. 3.14, Table 3.11).
    """

    number = (1, 4, 5, 21)
    name = "Ex. 3.10"
    param_names = ()
    source = FormulaSource(
        reference=(
            "Epperson, J. F. (2013). An Introduction to Numerical Methods and Analysis, 2nd edition. "
            "John Wiley & Sons, Hoboken, NJ. ISBN 978-1-118-36759-9."
        ),
        location="Ex. 3.10, 3.11, 3.14",
    )

    @staticmethod
    def parametrized_fun(x: float, c: float) -> float:
        """Evaluate the published function at ``x - c_scale*c``; category 1 states the rule for ``c_scale``."""
        x = x - 4.0 * c
        return x**4 - x - 1

    def interval_bounds(self) -> tuple[float, float]:
        """Return the formula's interval."""
        return (-2.0, 2.0)

    def recipes(self) -> tuple[ParamRecipe, ...]:
        """Return no recipe, since the published function has no parameters."""
        return ()

    cases = (
        FormulaTestCase.value(params={}, x=-0.8, c=0.0, expected=0.20960000000000015),
        FormulaTestCase.value(params={}, x=-0.8, c=0.25, expected=11.297600000000001),
        FormulaTestCase.interval_bounds(params={}, expected=(-2.0, 2.0)),
    )
