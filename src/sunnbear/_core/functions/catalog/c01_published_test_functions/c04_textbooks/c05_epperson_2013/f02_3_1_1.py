"""This module holds a formula of Epperson (2013).

The formula comes from the rows with the keys ``3.1-1, 3.1-3(a), 3.1-10; 3.2-2, 3.2-5(h); 3.3-3(h); 3.8-1, 3.8-2`` and
``3.1-2(c)`` in the survey of published test problems. A script generates this module from that survey: to change the
formula, change its source file in `data/literature_test_problems/sources/` and run `uv run python -m
scripts.literature_test_problems.formula_modules 2013_epperson`; do not edit this file.
"""

from sunnbear._core.functions.core import Formula, FormulaSource, FormulaTestCase, ParamRecipe, ParamTable

# SURVEY_FIELDS_HASH is a hash of this formula's survey fields; the tests recompute it from the
# survey, so that a test fails when the survey changes and this module is not regenerated.
SURVEY_FIELDS_HASH = "67f9c87e55e2befe"


class Epperson2013311(Formula):
    """This formula comes from Epperson (2013).

    The source prints 2 functions that differ only in the values of some constants; with those constants replaced by
    parameters, the 2 functions become 1 function, ``x^3 - k``:

    - 3.1-1, 3.1-3(a), 3.1-10; 3.2-2, 3.2-5(h); 3.3-3(h); 3.8-1, 3.8-2, with ``k = 2``: ``x^3 - 2``; the formula's
      interval is ``[0, 2]``
    - 3.1-2(c), with ``k = 3``: ``x^3 - 3``; the formula's interval is ``[0, 3]``

    3.1-1, 3.1-3(a), 3.1-10; 3.2-2, 3.2-5(h); 3.3-3(h); 3.8-1, 3.8-2: Bisection (3.1-1, 3.1-3) and regula falsi (3.1-10)
    on `[0, 2]`; Newton from `x0 = 1` (3.2-5, 3.3-3); secant from `x0 = 0, x1 = 1` and from `x0 = 1, x1 = 0` (3.8-1,
    3.8-2). 3.2-2 asks what its root computes.

    3.1-2(c): 3.1-2 asks for the root to an accuracy of 0.1 by bisection, by hand.
    """

    number = (1, 4, 5, 2)
    name = "3.1-1"
    param_names = ("k", "a", "b", "c_scale")
    source = FormulaSource(
        reference=(
            "Epperson, J. F. (2013). An Introduction to Numerical Methods and Analysis, 2nd edition. "
            "John Wiley & Sons, Hoboken, NJ. ISBN 978-1-118-36759-9."
        ),
        location="3.1-1, 3.1-3(a), 3.1-10; 3.2-2, 3.2-5(h); 3.3-3(h); 3.8-1, 3.8-2, 3.1-2(c)",
    )

    @staticmethod
    def parametrized_fun(x: float, c: float, k: float, a: float, b: float, c_scale: float) -> float:
        """Evaluate the published function at ``x - c_scale*c``; category 1 states the rule for ``c_scale``."""
        x = x - c_scale * c
        return x**3 - k

    def interval_bounds(self, k: float, a: float, b: float, c_scale: float) -> tuple[float, float]:
        """Return the interval of the tuple, its parameters ``a`` and ``b``."""
        return (a, b)

    def recipes(self) -> tuple[ParamRecipe, ...]:
        """Return the published parameter values."""
        return (ParamTable(names=("k", "a", "b", "c_scale"), rows=((2.0, 0.0, 2.0, 2.0), (3.0, 0.0, 3.0, 3.0))),)

    cases = (
        FormulaTestCase.value(params={"k": 2.0, "a": 0.0, "b": 2.0, "c_scale": 2.0}, x=0.6, c=0.0, expected=-1.784),
        FormulaTestCase.value(params={"k": 2.0, "a": 0.0, "b": 2.0, "c_scale": 2.0}, x=0.6, c=0.25, expected=-1.999),
        FormulaTestCase.value(params={"k": 3.0, "a": 0.0, "b": 3.0, "c_scale": 3.0}, x=0.9, c=0.0, expected=-2.271),
        FormulaTestCase.interval_bounds(params={"k": 2.0, "a": 0.0, "b": 2.0, "c_scale": 2.0}, expected=(0.0, 2.0)),
        FormulaTestCase.interval_bounds(params={"k": 3.0, "a": 0.0, "b": 3.0, "c_scale": 3.0}, expected=(0.0, 3.0)),
    )
