"""This module holds a formula of Epperson (2013).

The formula comes from the row with the key ``3.1-3(f); 3.2-5(c); 3.3-3(a)`` in the survey of published test problems. A
script generates this module from that survey: to change the formula, change its source file in
`data/literature_test_problems/sources/` and run `uv run python -m scripts.literature_test_problems.formula_modules
2013_epperson`; do not edit this file.
"""

import math

from sunnbear._core.functions.core import Formula, FormulaSource, FormulaTestCase, ParamRecipe

# SURVEY_FIELDS_HASH is a hash of this formula's survey fields; the tests recompute it from the
# survey, so that a test fails when the survey changes and this module is not regenerated.
SURVEY_FIELDS_HASH = "2a4e7ca3fd1dc5c3"


class Epperson2013313F(Formula):
    """This formula evaluates the published function at ``x - (b - a)*c``, where ``[a, b]`` is its interval.

    The survey writes the source's function as ``1 - 2*x*exp(-x/2)``; the formula's interval is ``[0, 2]``.

    Bisection to `1E-6`; Newton from `x0 = 0`.
    """

    number = (1, 4, 5, 6)
    name = "3.1-3(f)"
    param_names = ()
    source = FormulaSource(
        reference=(
            "Epperson, J. F. (2013). An Introduction to Numerical Methods and Analysis, 2nd edition. "
            "John Wiley & Sons, Hoboken, NJ. ISBN 978-1-118-36759-9."
        ),
        location="3.1-3(f); 3.2-5(c); 3.3-3(a)",
    )

    @staticmethod
    def parametrized_fun(x: float, c: float) -> float:
        """Evaluate the published function at ``x - (b - a)*c``, where ``[a, b]`` is the formula's interval."""
        x = x - 2.0 * c
        return 1 - 2 * x * math.exp(-x / 2)

    def interval_bounds(self) -> tuple[float, float]:
        """Return the formula's interval."""
        return (0.0, 2.0)

    def recipes(self) -> tuple[ParamRecipe, ...]:
        """Return no recipe, since the published function has no parameters."""
        return ()

    cases = (
        FormulaTestCase.value(params={}, x=0.6, c=0.0, expected=0.11101813518193858),
        FormulaTestCase.value(params={}, x=0.6, c=0.25, expected=0.8097541150998573),
        FormulaTestCase.interval_bounds(params={}, expected=(0.0, 2.0)),
    )
