"""This module holds a formula of Atkinson (1989).

The formula comes from the row with the key ``(1.3.6)`` in the survey of published test problems. A script generates
this module from that survey: to change the formula, change its source file in `data/literature_test_problems/sources/`
and run `uv run python -m scripts.literature_test_problems.formula_modules 1989_atkinson`; do not edit this file.
"""

from sunnbear._core.functions.core import Formula, FormulaSource, FormulaTestCase, ParamRecipe, ParamTable

# SURVEY_FIELDS_HASH is a hash of this formula's survey fields; the tests recompute it from the
# survey, so that a test fails when the survey changes and this module is not regenerated.
SURVEY_FIELDS_HASH = "fed18a9113df8e9f"


class Atkinson1989136(Formula):
    """This formula evaluates the published function at ``x - (b - a)*c``, where ``[a, b]`` is its interval.

    The survey writes the source's function as ``x^3 - 3*x^2 + 3*x - 1``; the formula's intervals are `[0, 2]`; `[0.998,
    1.002]`.

    Equals `(x - 1)^3`. Chapter 1 evaluates it in single precision: at 640 points of `[0.998, 1.002]` the values form a
    band around 0 (Figures 1.1–1.2).
    """

    number = (1, 4, 1, 2)
    name = "(1.3.6)"
    param_names = ("a", "b")
    source = FormulaSource(
        reference=(
            "Atkinson, K. E. (1989). An Introduction to Numerical Analysis, 2nd edition. John Wiley & "
            "Sons, New York. ISBN 0-471-62489-6."
        ),
        location="(1.3.6)",
    )

    @staticmethod
    def parametrized_fun(x: float, c: float, a: float, b: float) -> float:
        """Evaluate the published function at ``x - (b - a)*c``, where ``[a, b]`` is the formula's interval."""
        x = x - (b - a) * c
        return x**3 - 3 * x**2 + 3 * x - 1

    def interval_bounds(self, a: float, b: float) -> tuple[float, float]:
        """Return the interval of the tuple, its parameters ``a`` and ``b``."""
        return (a, b)

    def recipes(self) -> tuple[ParamRecipe, ...]:
        """Return the published parameter values."""
        return (ParamTable(names=("a", "b"), rows=((0.0, 2.0), (0.998, 1.002))),)

    cases = (
        FormulaTestCase.value(params={"a": 0.0, "b": 2.0}, x=0.6, c=0.0, expected=-0.06400000000000002),
        FormulaTestCase.value(params={"a": 0.0, "b": 2.0}, x=0.6, c=0.25, expected=-0.7290000000000001),
        FormulaTestCase.value(params={"a": 0.998, "b": 1.002}, x=1.0014, c=0.0, expected=2.744000000000399e-09),
        FormulaTestCase.interval_bounds(params={"a": 0.0, "b": 2.0}, expected=(0.0, 2.0)),
        FormulaTestCase.interval_bounds(params={"a": 0.998, "b": 1.002}, expected=(0.998, 1.002)),
    )
