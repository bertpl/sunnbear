"""This module holds a formula of Moler (2004).

The formula comes from the row with the key ``§4.3, §4.4; Ex. 4.1, 4.8`` in the survey of published test problems. A
script generates this module from that survey: to change the formula, change its source file in
`data/literature_test_problems/sources/` and run `uv run python -m scripts.literature_test_problems.formula_modules
2004_moler`; do not edit this file.
"""

import math

from sunnbear._core.functions.core import Formula, FormulaSource, FormulaTestCase, ParamRecipe, ParamTable
from sunnbear._core.utils.math_functions import sign

# SURVEY_FIELDS_HASH is a hash of this formula's survey fields; the tests recompute it from the
# survey, so that a test fails when the survey changes and this module is not regenerated.
SURVEY_FIELDS_HASH = "a802aba9681ab005"


class Moler200443(Formula):
    """This formula evaluates the published function at ``x - (b - a)*c``, where ``[a, b]`` is its interval.

    The survey writes the source's function as ``sign(x - a)*sqrt(abs(x - a))``, with the parameters `a` free; `a = 2`
    in Figure 4.1 and Ex. 4.1; the formula's intervals are `[0, 4]` (Figure 4.1); `[1, 4]` (Ex. 4.1).

    The formula's parameter ``a_`` is the source's ``a``, renamed because ``[a, b]`` names the formula's interval.

    §4.3 derives it as the function on which Newton's method cycles forever around its zero `x = a`; the convergence
    theory for Newton's method fails on it because `f'(x)` is unbounded as `x` tends to `a`. Figure 4.1 plots it with
    `ezplot` on `[0, 4]`. §4.4 and Ex. 4.8 ask how the secant method behaves on it.
    """

    number = (1, 4, 3, 4)
    name = "§4.3"
    param_names = ("a_", "a", "b")
    source = FormulaSource(
        reference=(
            "Moler, C. B. (2004). Numerical Computing with MATLAB. SIAM, Philadelphia (print edition); "
            "The MathWorks, Natick, MA (electronic edition). ISBN 0-89871-560-1. The author's web "
            "edition, 1 PDF per chapter: https://www.mathworks.com/moler/chapters.html; chapter 4: "
            "https://www.mathworks.com/content/dam/mathworks/mathworks-dot-com/moler/zeros.pdf."
        ),
        location="§4.3, §4.4; Ex. 4.1, 4.8",
    )

    @staticmethod
    def parametrized_fun(x: float, c: float, a_: float, a: float, b: float) -> float:
        """Evaluate the published function at ``x - (b - a)*c``, where ``[a, b]`` is the formula's interval."""
        x = x - (b - a) * c
        return sign(x - a_) * math.sqrt(abs(x - a_))

    def interval_bounds(self, a_: float, a: float, b: float) -> tuple[float, float]:
        """Return the interval of the tuple, its parameters ``a`` and ``b``."""
        return (a, b)

    def recipes(self) -> tuple[ParamRecipe, ...]:
        """Return the published parameter values."""
        return (ParamTable(names=("a_", "a", "b"), rows=((2.0, 0.0, 4.0), (2.0, 1.0, 4.0))),)

    cases = (
        FormulaTestCase.value(params={"a_": 2.0, "a": 0.0, "b": 4.0}, x=1.2, c=0.0, expected=-0.8944271909999159),
        FormulaTestCase.value(params={"a_": 2.0, "a": 0.0, "b": 4.0}, x=1.2, c=0.25, expected=-1.3416407864998738),
        FormulaTestCase.value(params={"a_": 2.0, "a": 1.0, "b": 4.0}, x=1.9, c=0.0, expected=-0.31622776601683805),
        FormulaTestCase.interval_bounds(params={"a_": 2.0, "a": 0.0, "b": 4.0}, expected=(0.0, 4.0)),
        FormulaTestCase.interval_bounds(params={"a_": 2.0, "a": 1.0, "b": 4.0}, expected=(1.0, 4.0)),
    )
