"""This module holds a formula of Moler (2004).

The formula comes from the row with the key ``Ex. 4.10(c)`` in the survey of published test problems. A script generates
this module from that survey: to change the formula, change its source file in `data/literature_test_problems/sources/`
and run `uv run python -m scripts.literature_test_problems.formula_modules 2004_moler`; do not edit this file.
"""

from sunnbear._core.functions.core import Formula, FormulaSource, FormulaTestCase, ParamRecipe
from sunnbear._core.utils.math_functions import bessel_j0, bessel_y0

# SURVEY_FIELDS_HASH is a hash of this formula's survey fields; the tests recompute it from the
# survey, so that a test fails when the survey changes and this module is not regenerated.
SURVEY_FIELDS_HASH = "f6944c28548af3fb"


class Moler2004Ex410C(Formula):
    """This formula evaluates the published function at ``x - (b - a)*c``, where ``[a, b]`` is its interval.

    The survey writes the source's function as ``J0(x) = Y0(x)``; the formula's interval is ``[0, 10*pi]``.

    All solutions between 0 and `10*pi`.
    """

    number = (1, 4, 3, 15)
    name = "Ex. 4.10(c)"
    param_names = ()
    source = FormulaSource(
        reference=(
            "Moler, C. B. (2004). Numerical Computing with MATLAB. SIAM, Philadelphia (print edition); "
            "The MathWorks, Natick, MA (electronic edition). ISBN 0-89871-560-1. The author's web "
            "edition, 1 PDF per chapter: https://www.mathworks.com/moler/chapters.html; chapter 4: "
            "https://www.mathworks.com/content/dam/mathworks/mathworks-dot-com/moler/zeros.pdf."
        ),
        location="Ex. 4.10(c)",
    )

    @staticmethod
    def parametrized_fun(x: float, c: float) -> float:
        """Evaluate the published function at ``x - (b - a)*c``, where ``[a, b]`` is the formula's interval."""
        x = x - 31.41592653589793 * c
        return (bessel_j0(x)) - (bessel_y0(x))

    def interval_bounds(self) -> tuple[float, float]:
        """Return the formula's interval."""
        return (0.0, 31.41592653589793)

    def recipes(self) -> tuple[ParamRecipe, ...]:
        """Return no recipe, since the published function has no parameters."""
        return ()

    cases = (
        FormulaTestCase.value(params={}, x=9.42478, c=0.0, expected=-0.36726657736486834),
        FormulaTestCase.value(params={}, x=9.42478, c=0.25, expected=0.061995667907528064),
        FormulaTestCase.interval_bounds(params={}, expected=(0.0, 31.41592653589793)),
    )
