"""This module holds a formula of Bradie (2006).

The formula comes from the row with the key ``Ex. 2.2; Fig. 2.3; Tables 2.2, 2.3, 2.5; §2.4 (pp. 98, 100); §2.5 (p.
109); 2.1-13; 2.5-15; 2.6-3`` in the survey of published test problems. A script generates this module from that survey:
to change the formula, change its source file in `data/literature_test_problems/sources/` and run `uv run python -m
scripts.literature_test_problems.formula_modules 2006_bradie`; do not edit this file.
"""

import math

from sunnbear._core.functions.core import Formula, FormulaSource, FormulaTestCase, ParamRecipe, ParamTable

# SURVEY_FIELDS_HASH is a hash of this formula's survey fields; the tests recompute it from the
# survey, so that a test fails when the survey changes and this module is not regenerated.
SURVEY_FIELDS_HASH = "ee2cf3267f4a83ee"


class Bradie2006Ex22(Formula):
    """This formula evaluates the published function at ``x - (b - a)*c``, where ``[a, b]`` is its interval.

    The survey writes the source's function as ``tan(pi*x) - x - 6``; the formula's intervals are `(0.40, 0.48)`; `[0,
    0.48]` (§2.4, p. 100); `[0, 0.5]` (Fig. 2.3).

    The second standard test problem: infinitely many roots; the smallest positive one is `0.4510472588`. Bisection and
    false position on the interval (Ex. 2.2, Tables 2.2, 2.3; Aitken on the false-position sequence in 2.6-3). Newton
    from `p0 = 0.48` converges in 5 iterations; from `p0 = 0.4` it does not converge in 5000; from `p0 = 0` it converges
    to the root `697.4995475` (p. 98). Secant from `p0 = 0.4, p1 = 0.48` (p. 109) and from `(0, 0.48)`, `(0.24, 0.48)`,
    `(0.4, 0.48)` (2.5-15). 2.1-13 seeks the next smallest positive root.
    """

    number = (1, 4, 4, 6)
    name = "Ex. 2.2"
    param_names = ("a", "b")
    source = FormulaSource(
        reference=(
            "Bradie, B. (2006). A Friendly Introduction to Numerical Analysis. Pearson Prentice Hall, "
            "Upper Saddle River, NJ. ISBN 0-13-013054-0."
        ),
        location=("Ex. 2.2; Fig. 2.3; Tables 2.2, 2.3, 2.5; §2.4 (pp. 98, 100); §2.5 (p. 109); 2.1-13; 2.5-15; 2.6-3"),
    )

    @staticmethod
    def parametrized_fun(x: float, c: float, a: float, b: float) -> float:
        """Evaluate the published function at ``x - (b - a)*c``, where ``[a, b]`` is the formula's interval."""
        x = x - (b - a) * c
        return math.tan(math.pi * x) - x - 6

    def interval_bounds(self, a: float, b: float) -> tuple[float, float]:
        """Return the interval of the tuple, its parameters ``a`` and ``b``."""
        return (a, b)

    def recipes(self) -> tuple[ParamRecipe, ...]:
        """Return the published parameter values."""
        return (ParamTable(names=("a", "b"), rows=((0.4, 0.48), (0.0, 0.48), (0.0, 0.5))),)

    cases = (
        FormulaTestCase.value(params={"a": 0.4, "b": 0.48}, x=0.424, c=0.0, expected=-2.315603156282293),
        FormulaTestCase.value(params={"a": 0.4, "b": 0.48}, x=0.424, c=0.25, expected=-3.189417921365975),
        FormulaTestCase.value(params={"a": 0.0, "b": 0.48}, x=0.144, c=0.0, expected=-5.657994647140798),
        FormulaTestCase.value(params={"a": 0.0, "b": 0.5}, x=0.15, c=0.0, expected=-5.640474550505571),
        FormulaTestCase.interval_bounds(params={"a": 0.4, "b": 0.48}, expected=(0.4, 0.48)),
        FormulaTestCase.interval_bounds(params={"a": 0.0, "b": 0.48}, expected=(0.0, 0.48)),
        FormulaTestCase.interval_bounds(params={"a": 0.0, "b": 0.5}, expected=(0.0, 0.5)),
    )
