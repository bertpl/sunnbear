"""This module holds a formula of Bradie (2006).

The formula comes from the row with the key ``2.2-9; 2.4-10; 2.5-10`` in the survey of published test problems. A script
generates this module from that survey: to change the formula, change its source file in
`data/literature_test_problems/sources/` and run `uv run python -m scripts.literature_test_problems.formula_modules
2006_bradie`; do not edit this file.
"""

from sunnbear._core.functions.core import Formula, FormulaSource, FormulaTestCase, ParamRecipe, ParamTable

# SURVEY_FIELDS_HASH is a hash of this formula's survey fields; the tests recompute it from the
# survey, so that a test fails when the survey changes and this module is not regenerated.
SURVEY_FIELDS_HASH = "475aa629b9aa2e95"


class Bradie2006229(Formula):
    """This formula evaluates the published function at ``x - (b - a)*c``, where ``[a, b]`` is its interval.

    The survey writes the source's function as ``x^4 - 18*x^2 + 45``; the formula's intervals are `(1, 2)`; `(3, 4)`.

    Roots `sqrt(3)` and `sqrt(15)`. False position, Newton from `p0 = 1` and secant from `p0 = 1, p1 = 2` toward
    `sqrt(3)`; the exercises compare the order of convergence at the 2 roots.
    """

    number = (1, 4, 4, 24)
    name = "2.2-9"
    param_names = ("a", "b")
    source = FormulaSource(
        reference=(
            "Bradie, B. (2006). A Friendly Introduction to Numerical Analysis. Pearson Prentice Hall, "
            "Upper Saddle River, NJ. ISBN 0-13-013054-0."
        ),
        location="2.2-9; 2.4-10; 2.5-10",
    )

    @staticmethod
    def parametrized_fun(x: float, c: float, a: float, b: float) -> float:
        """Evaluate the published function at ``x - (b - a)*c``, where ``[a, b]`` is the formula's interval."""
        x = x - (b - a) * c
        return x**4 - 18 * x**2 + 45

    def interval_bounds(self, a: float, b: float) -> tuple[float, float]:
        """Return the interval of the tuple, its parameters ``a`` and ``b``."""
        return (a, b)

    def recipes(self) -> tuple[ParamRecipe, ...]:
        """Return the published parameter values."""
        return (ParamTable(names=("a", "b"), rows=((1.0, 2.0), (3.0, 4.0))),)

    cases = (
        FormulaTestCase.value(params={"a": 1.0, "b": 2.0}, x=1.3, c=0.0, expected=17.4361),
        FormulaTestCase.value(params={"a": 1.0, "b": 2.0}, x=1.3, c=0.25, expected=26.37050625),
        FormulaTestCase.value(params={"a": 3.0, "b": 4.0}, x=3.3, c=0.0, expected=-32.4279),
        FormulaTestCase.interval_bounds(params={"a": 1.0, "b": 2.0}, expected=(1.0, 2.0)),
        FormulaTestCase.interval_bounds(params={"a": 3.0, "b": 4.0}, expected=(3.0, 4.0)),
    )
