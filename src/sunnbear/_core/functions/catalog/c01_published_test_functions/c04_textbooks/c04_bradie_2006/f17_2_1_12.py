"""This module holds a formula of Bradie (2006).

The formula comes from the row with the key ``2.1-12; 2.2-7; 2.4-6; 2.5-8`` in the survey of published test problems. A
script generates this module from that survey: to change the formula, change its source file in
`data/literature_test_problems/sources/` and run `uv run python -m scripts.literature_test_problems.formula_modules
2006_bradie`; do not edit this file.
"""

from sunnbear._core.functions.core import Formula, FormulaSource, FormulaTestCase, ParamRecipe

# SURVEY_FIELDS_HASH is a hash of this formula's survey fields; the tests recompute it from the
# survey, so that a test fails when the survey changes and this module is not regenerated.
SURVEY_FIELDS_HASH = "57a2c03882029ea1"


class Bradie20062112(Formula):
    """This formula evaluates the published function at ``x - (b - a)*c``, where ``[a, b]`` is its interval.

    The survey writes the source's function as ``1/x - 37``; the formula's interval is `(0.01, 0.1)` (2.2-7, 2.4-6,
    2.5-8).

    Root `1/37`. 2.1-12 asks for 5 decimal places by bisection, with no interval.
    """

    number = (1, 4, 4, 17)
    name = "2.1-12"
    param_names = ()
    source = FormulaSource(
        reference=(
            "Bradie, B. (2006). A Friendly Introduction to Numerical Analysis. Pearson Prentice Hall, "
            "Upper Saddle River, NJ. ISBN 0-13-013054-0."
        ),
        location="2.1-12; 2.2-7; 2.4-6; 2.5-8",
    )

    @staticmethod
    def parametrized_fun(x: float, c: float) -> float:
        """Evaluate the published function at ``x - (b - a)*c``, where ``[a, b]`` is the formula's interval."""
        x = x - 0.09000000000000001 * c
        return 1 / x - 37

    def interval_bounds(self) -> tuple[float, float]:
        """Return the formula's interval."""
        return (0.01, 0.1)

    def recipes(self) -> tuple[ParamRecipe, ...]:
        """Return no recipe, since the published function has no parameters."""
        return ()

    cases = (
        FormulaTestCase.value(params={}, x=0.037, c=0.0, expected=-9.972972972972972),
        FormulaTestCase.value(params={}, x=0.037, c=0.25, expected=31.96551724137933),
        FormulaTestCase.interval_bounds(params={}, expected=(0.01, 0.1)),
    )
