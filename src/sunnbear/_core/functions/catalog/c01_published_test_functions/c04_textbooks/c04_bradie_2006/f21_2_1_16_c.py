"""This module holds a formula of Bradie (2006).

The formula comes from the row with the key ``2.1-16(c); 2.2-11(c); 2.3-16; 2.4-14(c); 2.5-18(c)`` in the survey of
published test problems. A script generates this module from that survey: to change the formula, change its source file
in `data/literature_test_problems/sources/` and run `uv run python -m scripts.literature_test_problems.formula_modules
2006_bradie`; do not edit this file.
"""

import math

from sunnbear._core.functions.core import Formula, FormulaSource, FormulaTestCase, ParamRecipe

# SURVEY_FIELDS_HASH is a hash of this formula's survey fields; the tests recompute it from the
# survey, so that a test fails when the survey changes and this module is not regenerated.
SURVEY_FIELDS_HASH = "486d7fc720fe74ce"


class Bradie20062116C(Formula):
    """This formula evaluates the published function at ``x - (b - a)*c``, where ``[a, b]`` is its interval.

    The survey writes the source's function as ``1.05 - 1.04*x + log(x)``; the formula's interval is `(1, 2)` (2.3-16).

    All real roots to `1E-6` by bisection, false position, Newton and secant. 2.3-16 compares 3 fixed-point iteration
    functions of the reader's choice for its unique zero on `(1, 2)`. 2.6-9 iterates its fixed-point form `x = (1.05 +
    log(x))/1.04`.
    """

    number = (1, 4, 4, 21)
    name = "2.1-16(c)"
    param_names = ()
    source = FormulaSource(
        reference=(
            "Bradie, B. (2006). A Friendly Introduction to Numerical Analysis. Pearson Prentice Hall, "
            "Upper Saddle River, NJ. ISBN 0-13-013054-0."
        ),
        location="2.1-16(c); 2.2-11(c); 2.3-16; 2.4-14(c); 2.5-18(c)",
    )

    @staticmethod
    def parametrized_fun(x: float, c: float) -> float:
        """Evaluate the published function at ``x - (b - a)*c``, where ``[a, b]`` is the formula's interval."""
        x = x - 1.0 * c
        return 1.05 - 1.04 * x + math.log(x)

    def interval_bounds(self) -> tuple[float, float]:
        """Return the formula's interval."""
        return (1.0, 2.0)

    def recipes(self) -> tuple[ParamRecipe, ...]:
        """Return no recipe, since the published function has no parameters."""
        return ()

    cases = (
        FormulaTestCase.value(params={}, x=1.3, c=0.0, expected=-0.03963573553250896),
        FormulaTestCase.value(params={}, x=1.3, c=0.25, expected=0.006790164169431999),
        FormulaTestCase.interval_bounds(params={}, expected=(1.0, 2.0)),
    )
