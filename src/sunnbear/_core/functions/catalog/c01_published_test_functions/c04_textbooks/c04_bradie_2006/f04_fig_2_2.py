"""This module holds a formula of Bradie (2006).

The formula comes from the row with the key ``Fig. 2.2`` in the survey of published test problems. A script generates
this module from that survey: to change the formula, change its source file in `data/literature_test_problems/sources/`
and run `uv run python -m scripts.literature_test_problems.formula_modules 2006_bradie`; do not edit this file.
"""

from sunnbear._core.functions.core import Formula, FormulaSource, FormulaTestCase, ParamRecipe

# SURVEY_FIELDS_HASH is a hash of this formula's survey fields; the tests recompute it from the
# survey, so that a test fails when the survey changes and this module is not regenerated.
SURVEY_FIELDS_HASH = "553c21687ac2fc8a"


class Bradie2006Fig22(Formula):
    """This formula comes from Bradie (2006).

    The survey writes the source's function as ``(x - 1)^7``; the formula's interval is `[0, 2]` (Fig. 2.2).

    Root 1. Figure only, plotted on `[0, 2]`: its flat plateau means that `abs(f) < 1E-7` only guarantees `x` within
    `1E-1` of the root.
    """

    number = (1, 4, 4, 4)
    name = "Fig. 2.2"
    param_names = ()
    source = FormulaSource(
        reference=(
            "Bradie, B. (2006). A Friendly Introduction to Numerical Analysis. Pearson Prentice Hall, "
            "Upper Saddle River, NJ. ISBN 0-13-013054-0."
        ),
        location="Fig. 2.2",
    )

    @staticmethod
    def parametrized_fun(x: float, c: float) -> float:
        """Evaluate the published function at ``x - c_scale*c``; category 1 states the rule for ``c_scale``."""
        x = x - 2.0 * c
        return (x - 1) ** 7

    def interval_bounds(self) -> tuple[float, float]:
        """Return the formula's interval."""
        return (0.0, 2.0)

    def recipes(self) -> tuple[ParamRecipe, ...]:
        """Return no recipe, since the published function has no parameters."""
        return ()

    test_cases = (
        FormulaTestCase.value(params={}, x=0.6, c=0.0, expected=-0.0016384000000000006),
        FormulaTestCase.value(params={}, x=0.6, c=0.25, expected=-0.4782969000000001),
        FormulaTestCase.interval_bounds(params={}, expected=(0.0, 2.0)),
    )
