"""This module holds a formula of Chapra, Canale (2015).

The formula comes from the row with the key ``§7.7.1, Fig. 7.6; Ex. 7.4; §7.7.3, Fig. 7.7`` in the survey of published
test problems. A script generates this module from that survey: to change the formula, change its source file in
`data/literature_test_problems/sources/` and run `uv run python -m scripts.literature_test_problems.formula_modules
2015_chapra`; do not edit this file.
"""

import math

from sunnbear._core.functions.core import Formula, FormulaSource, FormulaTestCase, ParamRecipe, ParamTable

# SURVEY_FIELDS_HASH is a hash of this formula's survey fields; the tests recompute it from the
# survey, so that a test fails when the survey changes and this module is not regenerated.
SURVEY_FIELDS_HASH = "c0c9da36548d77f0"


class ChapraCanale2015771(Formula):
    """This formula evaluates the published function at ``x - (b - a)*c``, where ``[a, b]`` is its interval.

    The survey writes the source's function as ``x - cos(x)``; the formula's intervals are `[0, 2]` (Fig. 7.6); `[-10,
    10]` (Fig. 7.7).

    Root 0.739085. Excel: trial and error after a plot on `[0, 2]` (Fig. 7.6), and Goal Seek (Ex. 7.4); Mathcad's `root`
    from `x = 1`, with a plot on `[-10, 10]` (Fig. 7.7).
    """

    number = (1, 4, 6, 4)
    name = "§7.7.1"
    param_names = ("a", "b")
    source = FormulaSource(
        reference=(
            "Chapra, S. C., Canale, R. P. (2015). Numerical Methods for Engineers, 7th edition. "
            "McGraw-Hill Education. ISBN 978-0-07-339792-4. The 8th edition appeared in 2021; the rows "
            "follow the 7th."
        ),
        location="§7.7.1, Fig. 7.6; Ex. 7.4; §7.7.3, Fig. 7.7",
    )

    @staticmethod
    def parametrized_fun(x: float, c: float, a: float, b: float) -> float:
        """Evaluate the published function at ``x - (b - a)*c``, where ``[a, b]`` is the formula's interval."""
        x = x - (b - a) * c
        return x - math.cos(x)

    def interval_bounds(self, a: float, b: float) -> tuple[float, float]:
        """Return the interval of the tuple, its parameters ``a`` and ``b``."""
        return (a, b)

    def recipes(self) -> tuple[ParamRecipe, ...]:
        """Return the published parameter values."""
        return (ParamTable(names=("a", "b"), rows=((0.0, 2.0), (-10.0, 10.0))),)

    cases = (
        FormulaTestCase.value(params={"a": 0.0, "b": 2.0}, x=0.6, c=0.0, expected=-0.22533561490967832),
        FormulaTestCase.value(params={"a": 0.0, "b": 2.0}, x=0.6, c=0.25, expected=-0.8950041652780258),
        FormulaTestCase.value(params={"a": -10.0, "b": 10.0}, x=-4.0, c=0.0, expected=-3.346356379136388),
        FormulaTestCase.interval_bounds(params={"a": 0.0, "b": 2.0}, expected=(0.0, 2.0)),
        FormulaTestCase.interval_bounds(params={"a": -10.0, "b": 10.0}, expected=(-10.0, 10.0)),
    )
