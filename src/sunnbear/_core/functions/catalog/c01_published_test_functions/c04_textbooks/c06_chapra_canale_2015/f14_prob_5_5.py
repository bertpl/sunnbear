"""This module holds a formula of Chapra, Canale (2015).

The formula comes from the row with the key ``Prob. 5.5`` in the survey of published test problems. A script generates
this module from that survey: to change the formula, change its source file in `data/literature_test_problems/sources/`
and run `uv run python -m scripts.literature_test_problems.formula_modules 2015_chapra`; do not edit this file.
"""

import math

from sunnbear._core.functions.core import Formula, FormulaSource, FormulaTestCase, ParamRecipe

# SURVEY_FIELDS_HASH is a hash of this formula's survey fields; the tests recompute it from the
# survey, so that a test fails when the survey changes and this module is not regenerated.
SURVEY_FIELDS_HASH = "2ccd6af2fb1869c9"


class ChapraCanale2015Prob55(Formula):
    """This formula evaluates the published function at ``x - (b - a)*c``, where ``[a, b]`` is its interval.

    The survey writes the source's function as ``sin(x) = x^2``; the formula's interval is ``[0.5, 1]``.

    The first nontrivial root, graphically and by bisection to `es = 2%`.
    """

    number = (1, 4, 6, 14)
    name = "Prob. 5.5"
    param_names = ()
    source = FormulaSource(
        reference=(
            "Chapra, S. C., Canale, R. P. (2015). Numerical Methods for Engineers, 7th edition. "
            "McGraw-Hill Education. ISBN 978-0-07-339792-4. The 8th edition appeared in 2021; the rows "
            "follow the 7th."
        ),
        location="Prob. 5.5",
    )

    @staticmethod
    def parametrized_fun(x: float, c: float) -> float:
        """Evaluate the published function at ``x - (b - a)*c``, where ``[a, b]`` is the formula's interval."""
        x = x - 0.5 * c
        return (math.sin(x)) - (x**2)

    def interval_bounds(self) -> tuple[float, float]:
        """Return the formula's interval."""
        return (0.5, 1.0)

    def recipes(self) -> tuple[ParamRecipe, ...]:
        """Return no recipe, since the published function has no parameters."""
        return ()

    cases = (
        FormulaTestCase.value(params={}, x=0.65, c=0.0, expected=0.18268640573603956),
        FormulaTestCase.value(params={}, x=0.65, c=0.25, expected=0.22558800467379783),
        FormulaTestCase.interval_bounds(params={}, expected=(0.5, 1.0)),
    )
