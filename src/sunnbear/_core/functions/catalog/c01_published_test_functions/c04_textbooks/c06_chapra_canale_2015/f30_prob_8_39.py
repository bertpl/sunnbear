"""This module holds a formula of Chapra, Canale (2015).

The formula comes from the row with the key ``Prob. 8.39`` in the survey of published test problems. A script generates
this module from that survey: to change the formula, change its source file in `data/literature_test_problems/sources/`
and run `uv run python -m scripts.literature_test_problems.formula_modules 2015_chapra`; do not edit this file.
"""

import math

from sunnbear._core.functions.core import Formula, FormulaSource, FormulaTestCase, ParamRecipe, ParamTable

# SURVEY_FIELDS_HASH is a hash of this formula's survey fields; the tests recompute it from the
# survey, so that a test fails when the survey changes and this module is not regenerated.
SURVEY_FIELDS_HASH = "a127d83a40c981be"


class ChapraCanale2015Prob839(Formula):
    """This formula evaluates the published function at ``x - (b - a)*c``, where ``[a, b]`` is its interval.

    The survey writes the source's function as ``v = u*log(m0/(m0 - q*t)) - g*t``, with the parameters `u = 2200` m/s,
    `m0 = 160000` kg, `q = 2680` kg/s, `g = 9.81` m/s^2, `v = 1000` m/s; the formula's interval is ``[10, 50]``.

    Unknown `t`, the time at which the velocity is 1000 m/s, to within 1%; the book's hint gives the interval. The book
    prints `ln`.
    """

    number = (1, 4, 6, 30)
    name = "Prob. 8.39"
    param_names = ("u", "m0", "q", "g", "v")
    source = FormulaSource(
        reference=(
            "Chapra, S. C., Canale, R. P. (2015). Numerical Methods for Engineers, 7th edition. "
            "McGraw-Hill Education. ISBN 978-0-07-339792-4. The 8th edition appeared in 2021; the rows "
            "follow the 7th."
        ),
        location="Prob. 8.39",
    )

    @staticmethod
    def parametrized_fun(x: float, c: float, u: float, m0: float, q: float, g: float, v: float) -> float:
        """Evaluate the published function at ``x - (b - a)*c``, where ``[a, b]`` is the formula's interval."""
        x = x - 40.0 * c
        return (v) - (u * math.log(m0 / (m0 - q * x)) - g * x)

    def interval_bounds(self, u: float, m0: float, q: float, g: float, v: float) -> tuple[float, float]:
        """Return the formula's interval."""
        return (10.0, 50.0)

    def recipes(self) -> tuple[ParamRecipe, ...]:
        """Return the published parameter values."""
        return (ParamTable(names=("u", "m0", "q", "g", "v"), rows=((2200.0, 160000.0, 2680.0, 9.81, 1000.0),)),)

    cases = (
        FormulaTestCase.value(
            params={"u": 2200.0, "m0": 160000.0, "q": 2680.0, "g": 9.81, "v": 1000.0},
            x=22.0,
            c=0.0,
            expected=204.57385817849925,
        ),
        FormulaTestCase.value(
            params={"u": 2200.0, "m0": 160000.0, "q": 2680.0, "g": 9.81, "v": 1000.0},
            x=22.0,
            c=0.25,
            expected=624.0524669251027,
        ),
        FormulaTestCase.interval_bounds(
            params={"u": 2200.0, "m0": 160000.0, "q": 2680.0, "g": 9.81, "v": 1000.0}, expected=(10.0, 50.0)
        ),
    )
