"""This module holds a formula of Chapra, Canale (2015).

The formula comes from the row with the key ``Prob. 5.1`` in the survey of published test problems. A script generates
this module from that survey: to change the formula, change its source file in `data/literature_test_problems/sources/`
and run `uv run python -m scripts.literature_test_problems.formula_modules 2015_chapra`; do not edit this file.
"""

from sunnbear._core.functions.core import Formula, FormulaSource, FormulaTestCase, ParamRecipe

# SURVEY_FIELDS_HASH is a hash of this formula's survey fields; the tests recompute it from the
# survey, so that a test fails when the survey changes and this module is not regenerated.
SURVEY_FIELDS_HASH = "0209b855f8db05c0"


class ChapraCanale2015Prob51(Formula):
    """This formula comes from Chapra, Canale (2015).

    The survey writes the source's function as ``-0.5*x^2 + 2.5*x + 4.5``; the formula's interval is ``[5, 10]``.

    The real roots, graphically and by the quadratic formula; 3 bisection iterations for the highest root.
    """

    number = (1, 4, 6, 10)
    name = "Prob. 5.1"
    param_names = ()
    source = FormulaSource(
        reference=(
            "Chapra, S. C., Canale, R. P. (2015). Numerical Methods for Engineers, 7th edition. "
            "McGraw-Hill Education, New York, NY. ISBN 978-0-07-339792-4. The 8th edition appeared in "
            "2021."
        ),
        location="Prob. 5.1",
    )

    @staticmethod
    def parametrized_fun(x: float, c: float) -> float:
        """Evaluate the published function at ``x - c_scale*c``; category 1 states the rule for ``c_scale``."""
        x = x - 5.0 * c
        return -0.5 * x**2 + 2.5 * x + 4.5

    def interval_bounds(self) -> tuple[float, float]:
        """Return the formula's interval."""
        return (5.0, 10.0)

    def recipes(self) -> tuple[ParamRecipe, ...]:
        """Return no recipe, since the published function has no parameters."""
        return ()

    test_cases = (
        FormulaTestCase.value(params={}, x=6.5, c=0.0, expected=-0.375),
        FormulaTestCase.value(params={}, x=6.5, c=0.25, expected=3.84375),
        FormulaTestCase.interval_bounds(params={}, expected=(5.0, 10.0)),
    )
