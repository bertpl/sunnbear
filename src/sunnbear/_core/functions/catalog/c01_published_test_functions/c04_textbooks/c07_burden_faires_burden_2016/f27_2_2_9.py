"""This module holds a formula of Burden, Faires, Burden (2016).

The formula comes from the row with the key ``2.2-9`` in the survey of published test problems. A script generates this
module from that survey: to change the formula, change its source file in `data/literature_test_problems/sources/` and
run `uv run python -m scripts.literature_test_problems.formula_modules 2016_burden`; do not edit this file.
"""

import math

from sunnbear._core.functions.core import Formula, FormulaSource, FormulaTestCase, ParamRecipe

# SURVEY_FIELDS_HASH is a hash of this formula's survey fields; the tests recompute it from the
# survey, so that a test fails when the survey changes and this module is not regenerated.
SURVEY_FIELDS_HASH = "fa79aff9a22e41c8"


class BurdenFairesBurden2016229(Formula):
    """This formula comes from Burden, Faires, Burden (2016).

    The survey writes the source's function as ``x = pi + 0.5*sin(x/2)``; the formula's interval is ``[0, 2*pi]``.

    Unique fixed point on the interval by Theorem 2.3. Fixed-point iteration to `1E-2`, and Corollary 2.5's bound on the
    number of iterations compared with the number needed.
    """

    number = (1, 4, 7, 27)
    name = "2.2-9"
    param_names = ()
    source = FormulaSource(
        reference=(
            "Burden, R. L., Faires, J. D., Burden, A. M. (2016). Numerical Analysis, 10th edition. "
            "Cengage Learning, Boston, MA. ISBN 978-1-305-25366-7. The copyright page gives © 2016 and "
            "the print year 2014."
        ),
        location="2.2-9",
    )

    @staticmethod
    def parametrized_fun(x: float, c: float) -> float:
        """Evaluate the published function at ``x - c_scale*c``; category 1 states the rule for ``c_scale``."""
        x = x - 6.28 * c
        return (x) - (math.pi + 0.5 * math.sin(x / 2))

    def interval_bounds(self) -> tuple[float, float]:
        """Return the formula's interval."""
        return (0.0, 6.283185307179586)

    def recipes(self) -> tuple[ParamRecipe, ...]:
        """Return no recipe, since the published function has no parameters."""
        return ()

    test_cases = (
        FormulaTestCase.value(params={}, x=1.88496, c=0.0, expected=-1.661141798493021),
        FormulaTestCase.value(params={}, x=1.88496, c=0.25, expected=-2.905047598902962),
        FormulaTestCase.interval_bounds(params={}, expected=(0.0, 6.283185307179586)),
    )
