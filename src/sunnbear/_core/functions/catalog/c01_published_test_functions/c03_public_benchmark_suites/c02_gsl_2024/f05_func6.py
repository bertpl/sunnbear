"""This module holds a formula of GSL (2024).

The formula comes from the row with the key ``func6`` in the survey of published test problems. A script generates this
module from that survey: to change the formula, change its source file in `data/literature_test_problems/sources/` and
run `uv run python -m scripts.literature_test_problems.formula_modules gsl_roots_tests`; do not edit this file.
"""

from sunnbear._core.functions.core import Formula, FormulaSource, FormulaTestCase, ParamRecipe

# SURVEY_FIELDS_HASH is a hash of this formula's survey fields; the tests recompute it from the
# survey, so that a test fails when the survey changes and this module is not regenerated.
SURVEY_FIELDS_HASH = "dab17b984ccb05bc"


class Gsl2024Func6(Formula):
    """This formula evaluates the published function at ``x - (b - a)*c``, where ``[a, b]`` is its interval.

    The survey writes the source's function as ``(x - 1)^7``; the formula's interval is ``[0.9995, 1.0002]``.

    Starting point 0.9, run by `steffenson` only; derivative given
    """

    number = (1, 3, 2, 5)
    name = "func6"
    param_names = ()
    source = FormulaSource(
        reference=(
            "GNU Scientific Library (GSL), release 2.8, files `roots/test_funcs.c` and `roots/test.c` "
            "(copyright Reid Priedhorsky, Brian Gough), "
            "https://cgit.git.savannah.gnu.org/cgit/gsl.git/tree/roots/?h=release-2-8. The files cite "
            "no source for their functions."
        ),
        location="func6",
    )

    @staticmethod
    def parametrized_fun(x: float, c: float) -> float:
        """Evaluate the published function at ``x - (b - a)*c``, where ``[a, b]`` is the formula's interval."""
        x = x - 0.0006999999999999229 * c
        return (x - 1) ** 7

    def interval_bounds(self) -> tuple[float, float]:
        """Return the formula's interval."""
        return (0.9995, 1.0002)

    def recipes(self) -> tuple[ParamRecipe, ...]:
        """Return no recipe, since the published function has no parameters."""
        return ()

    # a case with `atol=0.0` has an expected value so small that the default `atol`
    # would accept any value near 0, 0 among them
    cases = (
        FormulaTestCase.value(params={}, x=0.99971, c=0.0, expected=-1.7249876309005193e-25, atol=0.0),
        FormulaTestCase.value(params={}, x=0.99971, c=0.25, expected=-4.700788051617231e-24, atol=0.0),
        FormulaTestCase.interval_bounds(params={}, expected=(0.9995, 1.0002)),
    )
