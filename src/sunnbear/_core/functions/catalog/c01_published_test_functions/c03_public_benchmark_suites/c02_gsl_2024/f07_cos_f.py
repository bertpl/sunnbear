"""This module holds a formula of GSL (2024).

The formula comes from the row with the key ``cos_f`` in the survey of published test problems. A script generates this
module from that survey: to change the formula, change its source file in `data/literature_test_problems/sources/` and
run `uv run python -m scripts.literature_test_problems.formula_modules gsl_roots_tests`; do not edit this file.
"""

import math

from sunnbear._core.functions.core import Formula, FormulaSource, FormulaTestCase, ParamRecipe, ParamTable

# SURVEY_FIELDS_HASH is a hash of this formula's survey fields; the tests recompute it from the
# survey, so that a test fails when the survey changes and this module is not regenerated.
SURVEY_FIELDS_HASH = "9358f3258859cbd6"


class Gsl2024CosF(Formula):
    """This formula evaluates the published function at ``x - (b - a)*c``, where ``[a, b]`` is its interval.

    The survey writes the source's function as ``cos(x)``; the formula's intervals are ``[0, 3], [-3, 0]``.

    Starting points 0.6, -2.5; derivative given
    """

    number = (1, 3, 2, 7)
    name = "cos_f"
    param_names = ("a", "b")
    source = FormulaSource(
        reference=(
            "GNU Scientific Library (GSL), release 2.8, files `roots/test_funcs.c` and `roots/test.c` "
            "(copyright Reid Priedhorsky, Brian Gough), "
            "https://cgit.git.savannah.gnu.org/cgit/gsl.git/tree/roots/?h=release-2-8. The files cite "
            "no source for their functions."
        ),
        location="cos_f",
    )

    @staticmethod
    def parametrized_fun(x: float, c: float, a: float, b: float) -> float:
        """Evaluate the published function at ``x - (b - a)*c``, where ``[a, b]`` is the formula's interval."""
        x = x - (b - a) * c
        return math.cos(x)

    def interval_bounds(self, a: float, b: float) -> tuple[float, float]:
        """Return the interval of the tuple, its parameters ``a`` and ``b``."""
        return (a, b)

    def recipes(self) -> tuple[ParamRecipe, ...]:
        """Return the published parameter values."""
        return (ParamTable(names=("a", "b"), rows=((0.0, 3.0), (-3.0, 0.0))),)

    cases = (
        FormulaTestCase.value(params={"a": 0.0, "b": 3.0}, x=0.9, c=0.0, expected=0.6216099682706644),
        FormulaTestCase.value(params={"a": 0.0, "b": 3.0}, x=0.9, c=0.25, expected=0.9887710779360422),
        FormulaTestCase.value(params={"a": -3.0, "b": 0.0}, x=-2.1, c=0.0, expected=-0.5048461045998576),
        FormulaTestCase.interval_bounds(params={"a": 0.0, "b": 3.0}, expected=(0.0, 3.0)),
        FormulaTestCase.interval_bounds(params={"a": -3.0, "b": 0.0}, expected=(-3.0, 0.0)),
    )
