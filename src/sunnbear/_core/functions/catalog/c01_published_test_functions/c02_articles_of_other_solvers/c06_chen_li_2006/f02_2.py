"""This module holds the formula that Chen, Li (2006) labels 2.

A script generates this module from the survey of published test problems: to change the formula, change its source file
in `data/literature_test_problems/sources/` and run `uv run python -m scripts.literature_test_problems.formula_modules
2006_chen_li`; do not edit this file.
"""

import math

from sunnbear._core.functions.core import Formula, FormulaSource, FormulaTestCase, ParamRecipe

# SURVEY_FIELDS_HASH is a hash of this formula's survey fields; the tests recompute it from the
# survey, so that a test fails when the survey changes and this module is not regenerated.
SURVEY_FIELDS_HASH = "f7584f6c25278d86"


class ChenLi20062(Formula):
    """This formula evaluates the published function at ``x - (b - a)*c``, where ``[a, b]`` is its interval.

    The survey writes the source's function as ``x - exp(sin(x)) + 1``; the formula's interval is ``[1, 4]``.

    `x0 = 4`. Root 1.69681.
    """

    number = (1, 2, 6, 2)
    name = "2"
    param_names = ()
    source = FormulaSource(
        reference=(
            "Chen, J., Li, W. (2007). An improved exponential regula falsi methods with quadratic "
            "convergence of both diameter and point for solving nonlinear equations. Applied Numerical "
            "Mathematics 57(1), 80–88. Published online 14 February 2006. "
            "https://doi.org/10.1016/j.apnum.2006.01.001. The article prints the volume and the year "
            "2007 but no issue number; the issue number is Crossref's. The year 2006 of the title "
            "follows the online date that the article prints; the issue is dated 2007."
        ),
        location="2",
    )

    @staticmethod
    def parametrized_fun(x: float, c: float) -> float:
        """Evaluate the published function at ``x - (b - a)*c``, where ``[a, b]`` is the formula's interval."""
        x = x - 3.0 * c
        return x - math.exp(math.sin(x)) + 1

    def interval_bounds(self) -> tuple[float, float]:
        """Return the formula's interval."""
        return (1.0, 4.0)

    def recipes(self) -> tuple[ParamRecipe, ...]:
        """Return no recipe, since the published function has no parameters."""
        return ()

    cases = (
        FormulaTestCase.value(params={}, x=1.9, c=0.0, expected=0.3238395631529812),
        FormulaTestCase.value(params={}, x=1.9, c=0.25, expected=-0.34119855052789855),
        FormulaTestCase.interval_bounds(params={}, expected=(1.0, 4.0)),
    )
