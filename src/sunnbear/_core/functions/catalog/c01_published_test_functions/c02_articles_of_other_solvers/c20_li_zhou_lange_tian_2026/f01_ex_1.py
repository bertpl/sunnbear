"""This module holds a formula of Li, Zhou, Lange, Tian (2026).

The formula comes from the row with the key ``Ex. 1`` in the survey of published test problems. A script generates this
module from that survey: to change the formula, change its source file in `data/literature_test_problems/sources/` and
run `uv run python -m scripts.literature_test_problems.formula_modules 2026_li_upper_crossing`; do not edit this file.
"""

import math

from sunnbear._core.functions.core import Formula, FormulaSource, FormulaTestCase, ParamRecipe, ParamTable

# SURVEY_FIELDS_HASH is a hash of this formula's survey fields; the tests recompute it from the
# survey, so that a test fails when the survey changes and this module is not regenerated.
SURVEY_FIELDS_HASH = "9721bc40289d6a39"


class LiZhouLangeTian2026Ex1(Formula):
    """This formula comes from Li, Zhou, Lange, Tian (2026).

    The survey writes the source's function as ``cos(0.5*pi*x) - x``; the formula's intervals are `x` in R; starting
    values `x(0) = -1, 2`; `[-2, 1]` (Figure 1(a)); `[0, 4]` (Figure 1(b)).

    Stated root `0.594612`. Table 1, Fig. 1.
    """

    number = (1, 2, 20, 1)
    name = "Ex. 1"
    param_names = ("a", "b", "c_scale")
    source = FormulaSource(
        reference=(
            "Li, X.-J., Zhou, H., Lange, K., Tian, G.-L. (2026). The upper–crossing/solution (US) "
            "algorithm with strongly stable convergence and an acceleration technique for root–finding "
            "problems. Statistics and Computing 36(4), 197. https://doi.org/10.1007/s11222-026-10902-z."
            " Preprint: arXiv 2212.00797v2 (8 November 2025), https://arxiv.org/abs/2212.00797v2. The "
            "authors' R code: https://github.com/Xunjian-Li/US-algorithm.git."
        ),
        location="Ex. 1",
    )

    @staticmethod
    def parametrized_fun(x: float, c: float, a: float, b: float, c_scale: float) -> float:
        """Evaluate the published function at ``x - c_scale*c``; category 1 states the rule for ``c_scale``."""
        x = x - c_scale * c
        return math.cos(0.5 * math.pi * x) - x

    def interval_bounds(self, a: float, b: float, c_scale: float) -> tuple[float, float]:
        """Return the interval of the tuple, its parameters ``a`` and ``b``."""
        return (a, b)

    def recipes(self) -> tuple[ParamRecipe, ...]:
        """Return the published parameter values."""
        return (ParamTable(names=("a", "b", "c_scale"), rows=((-2.0, 1.0, 3.0), (0.0, 4.0, 4.0))),)

    cases = (
        FormulaTestCase.value(params={"a": -2.0, "b": 1.0, "c_scale": 3.0}, x=-1.1, c=0.0, expected=0.9435655349597691),
        FormulaTestCase.value(
            params={"a": -2.0, "b": 1.0, "c_scale": 3.0}, x=-1.1, c=0.25, expected=0.8776300796023234
        ),
        FormulaTestCase.value(params={"a": 0.0, "b": 4.0, "c_scale": 4.0}, x=1.2, c=0.0, expected=-1.5090169943749474),
        FormulaTestCase.interval_bounds(params={"a": -2.0, "b": 1.0, "c_scale": 3.0}, expected=(-2.0, 1.0)),
        FormulaTestCase.interval_bounds(params={"a": 0.0, "b": 4.0, "c_scale": 4.0}, expected=(0.0, 4.0)),
    )
