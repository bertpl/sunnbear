        FormulaTestCase.value(params={"a": 2.5, "b": 3.0}, x=2.65, c=0.25, expected=0.5419169962034848),
        FormulaTestCase.value(params={"a": 0.0, "b": 3.0}, x=0.9, c=0.0, expected=0.7950552616616401),
        FormulaTestCase.interval_bounds(params={"a": 2.5, "b": 3.0}, expected=(2.5, 3.0)),
