"""This module holds the formula that Sabharwal (2019) labels T2.1 and T2.2 and T2.3.

A script generates this module from the survey of published test problems: to change the formula, change its source file
in `data/literature_test_problems/sources/` and run `uv run python -m scripts.literature_test_problems.formula_modules
2019_sabharwal`; do not edit this file.
"""

from sunnbear._core.functions.core import Formula, FormulaSource, FormulaTestCase, ParamRecipe, ParamTable

# SURVEY_FIELDS_HASH is a hash of this formula's survey fields; the tests recompute it from the
# survey, so that a test fails when the survey changes and this module is not regenerated.
SURVEY_FIELDS_HASH = "0fc1b09a53e0fe39"


class Sabharwal2019T21(Formula):
    """This formula evaluates the published function at ``x - (b - a)*c``, where ``[a, b]`` is its interval.

    The source prints 1 function in 3 rows, each with its own parameter values; with each row's values replaced by
    parameters, that function is ``x^2 - a``:

    - T2.1, with ``a = 3``: ``x^2 - 3``; the formula's interval is ``[1, 2]``
    - T2.2, with ``a = 5``: ``x^2 - 5``; the formula's interval is ``[2, 7]``
    - T2.3, with ``a = 10``: ``x^2 - 10``; the formula's interval is ``[3, 4]``

    The formula's parameter ``a_`` is the source's ``a``, renamed because the formula uses ``a`` for another value.
    """

    number = (1, 2, 13, 5)
    name = "T2.1"
    param_names = ("a_", "a", "b")
    source = FormulaSource(
        reference=(
            "Sabharwal, C. L. (2019). Blended Root Finding Algorithm Outperforms Bisection and Regula "
            "Falsi Algorithms. Mathematics 7(11), 1118. https://doi.org/10.3390/math7111118."
        ),
        location="T2.1, T2.2, T2.3",
    )

    @staticmethod
    def parametrized_fun(x: float, c: float, a_: float, a: float, b: float) -> float:
        """Evaluate the published function at ``x - (b - a)*c``, where ``[a, b]`` is the formula's interval."""
        x = x - (b - a) * c
        return x**2 - a_

    def interval_bounds(self, a_: float, a: float, b: float) -> tuple[float, float]:
        """Return the interval of the tuple, its parameters ``a`` and ``b``."""
        return (a, b)

    def recipes(self) -> tuple[ParamRecipe, ...]:
        """Return the published parameter values."""
        return (ParamTable(names=("a_", "a", "b"), rows=((3.0, 1.0, 2.0), (5.0, 2.0, 7.0), (10.0, 3.0, 4.0))),)

    cases = (
        FormulaTestCase.value(params={"a_": 3.0, "a": 1.0, "b": 2.0}, x=1.3, c=0.0, expected=-1.3099999999999998),
        FormulaTestCase.value(params={"a_": 3.0, "a": 1.0, "b": 2.0}, x=1.3, c=0.25, expected=-1.8975),
        FormulaTestCase.value(params={"a_": 5.0, "a": 2.0, "b": 7.0}, x=3.5, c=0.0, expected=7.25),
        FormulaTestCase.value(params={"a_": 10.0, "a": 3.0, "b": 4.0}, x=3.3, c=0.0, expected=0.8899999999999988),
        FormulaTestCase.interval_bounds(params={"a_": 3.0, "a": 1.0, "b": 2.0}, expected=(1.0, 2.0)),
        FormulaTestCase.interval_bounds(params={"a_": 5.0, "a": 2.0, "b": 7.0}, expected=(2.0, 7.0)),
        FormulaTestCase.interval_bounds(params={"a_": 10.0, "a": 3.0, "b": 4.0}, expected=(3.0, 4.0)),
    )
