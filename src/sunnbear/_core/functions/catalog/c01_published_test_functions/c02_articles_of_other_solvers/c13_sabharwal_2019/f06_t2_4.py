"""This module holds the formula that Sabharwal (2019) labels T2.4.

A script generates this module from the survey of published test problems: to change the formula, change its source file
in `data/literature_test_problems/sources/` and run `uv run python -m scripts.literature_test_problems.formula_modules
2019_sabharwal`; do not edit this file.
"""

from sunnbear._core.functions.core import Formula, FormulaSource, FormulaTestCase, ParamRecipe

# SURVEY_FIELDS_HASH is a hash of this formula's survey fields; the tests recompute it from the
# survey, so that a test fails when the survey changes and this module is not regenerated.
SURVEY_FIELDS_HASH = "cb5a96905c94836c"


class Sabharwal2019T24(Formula):
    """This formula evaluates the published function at ``x - (b - a)*c``, where ``[a, b]`` is its interval.

    The survey writes the source's function as ``x^2 - x - 2``; the formula's interval is ``[1, 4]``.

    The article's only results: Tables 1 and 3–7 and Figures 5–9 compare 5 methods on this function, with tolerance
    `0.00001`; Newton's method starts from `x0 = 1`, the secant method from `1` and `4`.
    """

    number = (1, 2, 13, 6)
    name = "T2.4"
    param_names = ()
    source = FormulaSource(
        reference=(
            "Sabharwal, C. L. (2019). Blended Root Finding Algorithm Outperforms Bisection and Regula "
            "Falsi Algorithms. Mathematics 7(11), 1118. https://doi.org/10.3390/math7111118."
        ),
        location="T2.4",
    )

    @staticmethod
    def parametrized_fun(x: float, c: float) -> float:
        """Evaluate the published function at ``x - (b - a)*c``, where ``[a, b]`` is the formula's interval."""
        x = x - 3.0 * c
        return x**2 - x - 2

    def interval_bounds(self) -> tuple[float, float]:
        """Return the formula's interval."""
        return (1.0, 4.0)

    def recipes(self) -> tuple[ParamRecipe, ...]:
        """Return no recipe, since the published function has no parameters."""
        return ()

    cases = (
        FormulaTestCase.value(params={}, x=1.9, c=0.0, expected=-0.29000000000000026),
        FormulaTestCase.value(params={}, x=1.9, c=0.25, expected=-1.8275000000000001),
        FormulaTestCase.interval_bounds(params={}, expected=(1.0, 4.0)),
    )
