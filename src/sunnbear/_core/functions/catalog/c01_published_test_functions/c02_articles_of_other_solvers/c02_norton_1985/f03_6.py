"""This module holds the formula that Norton (1985) labels 6.

A script generates this module from the survey of published test problems: to change the formula, change its source file
in `data/literature_test_problems/sources/` and run `uv run python -m scripts.literature_test_problems.formula_modules
1985_norton`; do not edit this file.
"""

import math

from sunnbear._core.functions.core import Formula, FormulaSource, FormulaTestCase, ParamRecipe, ParamTable

# SURVEY_FIELDS_HASH is a hash of this formula's survey fields; the tests recompute it from the
# survey, so that a test fails when the survey changes and this module is not regenerated.
SURVEY_FIELDS_HASH = "a6bd937763671823"


class Norton19856(Formula):
    """This formula evaluates the published function at ``x - (b - a)*c``, where ``[a, b]`` is its interval.

    The survey writes the source's function as ``(x - 1)*exp(-n*x) + x^n``, with the parameters ``n = 2, 5, 10, 20``;
    the formula's interval is ``[0, 1]``.

    Group I; the article: increasingly close to the x-axis for large `n`.
    """

    number = (1, 2, 2, 3)
    name = "6"
    param_names = ("n",)
    source = FormulaSource(
        reference=(
            "Norton, V. (1985). Algorithm 631: Finding a bracketed zero by Larkin's method of rational "
            "interpolation. ACM Transactions on Mathematical Software 11(2), 120–134. "
            "https://doi.org/10.1145/214392.214396. The author's Fortran code is Algorithm 631 of the "
            "Collected Algorithms of the ACM (CALGO), https://www.netlib.org/toms/631."
        ),
        location="6",
    )

    @staticmethod
    def parametrized_fun(x: float, c: float, n: float) -> float:
        """Evaluate the published function at ``x - (b - a)*c``, where ``[a, b]`` is the formula's interval."""
        x = x - 1.0 * c
        return (x - 1) * math.exp(-n * x) + x**n

    def interval_bounds(self, n: float) -> tuple[float, float]:
        """Return the formula's interval."""
        return (0.0, 1.0)

    def recipes(self) -> tuple[ParamRecipe, ...]:
        """Return the published parameter values."""
        return (ParamTable(names=("n",), rows=((2.0,), (5.0,), (10.0,), (20.0,))),)

    cases = (
        FormulaTestCase.value(params={"n": 2.0}, x=0.3, c=0.0, expected=-0.2941681452658185),
        FormulaTestCase.value(params={"n": 2.0}, x=0.3, c=0.25, expected=-0.8570955471341616),
        FormulaTestCase.value(params={"n": 5.0}, x=0.3, c=0.0, expected=-0.1537611121039009),
        FormulaTestCase.value(params={"n": 10.0}, x=0.3, c=0.0, expected=-0.03484504295750476),
        FormulaTestCase.value(params={"n": 20.0}, x=0.3, c=0.0, expected=-0.0017351264887986073),
        FormulaTestCase.interval_bounds(params={"n": 2.0}, expected=(0.0, 1.0)),
    )
