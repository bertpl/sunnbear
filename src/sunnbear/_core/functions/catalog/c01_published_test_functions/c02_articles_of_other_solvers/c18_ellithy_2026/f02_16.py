"""This module holds the formula that Ellithy (2026) labels 16 and 37.

A script generates this module from the survey of published test problems: to change the formula, change its source file
in `data/literature_test_problems/sources/` and run `uv run python -m scripts.literature_test_problems.formula_modules
2026_ellithy`; do not edit this file.
"""

import math

from sunnbear._core.functions.core import Formula, FormulaSource, FormulaTestCase, ParamRecipe, ParamTable

# SURVEY_FIELDS_HASH is a hash of this formula's survey fields; the tests recompute it from the
# survey, so that a test fails when the survey changes and this module is not regenerated.
SURVEY_FIELDS_HASH = "7dc063abf43cfed6"


class Ellithy202616(Formula):
    """This formula evaluates the published function at ``x - (b - a)*c``, where ``[a, b]`` is its interval.

    The source prints 1 function in 2 rows, each with its own parameter values; with each row's values replaced by
    parameters, that function is ``sin(a*x) - b*x``:

    - 16, with ``a = 10, b = 0.5``: ``sin(10*x) - 0.5*x``; the formula's interval is ``[0.1, 0.4]``
    - 37, with ``a = 20, b = 0.3``: ``sin(20*x) - 0.3*x``; the formula's interval is ``[0.05, 0.25]``

    The formula's parameter ``a_`` is the source's ``a``, renamed because the formula uses ``a`` for another value. The
    formula's parameter ``b_`` is the source's ``b``, renamed because the formula uses ``b`` for another value.
    """

    number = (1, 2, 18, 2)
    name = "16"
    param_names = ("a_", "b_", "a", "b")
    source = FormulaSource(
        reference=(
            "Ellithy, A. (2026). Four new multi-phase hybrid bracketing algorithms for numerical root "
            "finding. Journal of the Egyptian Mathematical Society 34(1), 91–115. "
            "https://doi.org/10.21608/joems.2026.440115.1078. Code and data: the author's repository "
            "https://github.com/Abdelrhman-Ellithy/hybridroots, at commit "
            "`7f22131ef4e1def3e3928dc6558f46f756d0a5ea`."
        ),
        location="16, 37",
    )

    @staticmethod
    def parametrized_fun(x: float, c: float, a_: float, b_: float, a: float, b: float) -> float:
        """Evaluate the published function at ``x - (b - a)*c``, where ``[a, b]`` is the formula's interval."""
        x = x - (b - a) * c
        return math.sin(a_ * x) - b_ * x

    def interval_bounds(self, a_: float, b_: float, a: float, b: float) -> tuple[float, float]:
        """Return the interval of the tuple, its parameters ``a`` and ``b``."""
        return (a, b)

    def recipes(self) -> tuple[ParamRecipe, ...]:
        """Return the published parameter values."""
        return (ParamTable(names=("a_", "b_", "a", "b"), rows=((10.0, 0.5, 0.1, 0.4), (20.0, 0.3, 0.05, 0.25))),)

    cases = (
        FormulaTestCase.value(
            params={"a_": 10.0, "b_": 0.5, "a": 0.1, "b": 0.4}, x=0.19, c=0.0, expected=0.8513000876874145
        ),
        FormulaTestCase.value(
            params={"a_": 10.0, "b_": 0.5, "a": 0.1, "b": 0.4}, x=0.19, c=0.25, expected=0.855263940260521
        ),
        FormulaTestCase.value(
            params={"a_": 20.0, "b_": 0.3, "a": 0.05, "b": 0.25}, x=0.11, c=0.0, expected=0.7754964038195902
        ),
        FormulaTestCase.interval_bounds(params={"a_": 10.0, "b_": 0.5, "a": 0.1, "b": 0.4}, expected=(0.1, 0.4)),
        FormulaTestCase.interval_bounds(params={"a_": 20.0, "b_": 0.3, "a": 0.05, "b": 0.25}, expected=(0.05, 0.25)),
    )
