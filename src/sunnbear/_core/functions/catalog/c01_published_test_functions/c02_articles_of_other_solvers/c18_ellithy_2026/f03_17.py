"""This module holds the formula that Ellithy (2026) labels 17 and 28 and 44.

A script generates this module from the survey of published test problems: to change the formula, change its source file
in `data/literature_test_problems/sources/` and run `uv run python -m scripts.literature_test_problems.formula_modules
2026_ellithy`; do not edit this file.
"""

import math

from sunnbear._core.functions.core import Formula, FormulaSource, FormulaTestCase, ParamRecipe, ParamTable

# SURVEY_FIELDS_HASH is a hash of this formula's survey fields; the tests recompute it from the
# survey, so that a test fails when the survey changes and this module is not regenerated.
SURVEY_FIELDS_HASH = "de909dab18fc4df7"


class Ellithy202617(Formula):
    """This formula evaluates the published function at ``x - (b - a)*c``, where ``[a, b]`` is its interval.

    The source prints 1 function in 3 rows, each with its own parameter values; with each row's values replaced by
    parameters, that function is ``x - e*sin(x) - M``:

    - 17, with ``e = 0.8, M = 1.2``: ``x - 0.8*sin(x) - 1.2``; the formula's interval is ``[1, 3]``
    - 28, with ``e = 0.5, M = 1``: ``x - 0.5 * sin(x) - 1``; the formula's interval is ``[0, 3]``
    - 44, with ``e = 0.99, M = 2``: ``x - 0.99 * sin(x) - 2.0``; the formula's interval is ``[2.0, 3.0]``

    44: The file's note: "Kepler Equation: Eccentric anomaly for e=0.99, Mean Anomaly=2.0".
    """

    number = (1, 2, 18, 3)
    name = "17"
    param_names = ("e", "M", "a", "b")
    source = FormulaSource(
        reference=(
            "Ellithy, A. (2026). Four new multi-phase hybrid bracketing algorithms for numerical root "
            "finding. Journal of the Egyptian Mathematical Society 34(1), 91–115. "
            "https://doi.org/10.21608/joems.2026.440115.1078. Code and data: the author's repository "
            "https://github.com/Abdelrhman-Ellithy/hybridroots, at commit "
            "`7f22131ef4e1def3e3928dc6558f46f756d0a5ea`."
        ),
        location="17, 28, 44",
    )

    @staticmethod
    def parametrized_fun(x: float, c: float, e: float, M: float, a: float, b: float) -> float:
        """Evaluate the published function at ``x - (b - a)*c``, where ``[a, b]`` is the formula's interval."""
        x = x - (b - a) * c
        return x - e * math.sin(x) - M

    def interval_bounds(self, e: float, M: float, a: float, b: float) -> tuple[float, float]:
        """Return the interval of the tuple, its parameters ``a`` and ``b``."""
        return (a, b)

    def recipes(self) -> tuple[ParamRecipe, ...]:
        """Return the published parameter values."""
        return (
            ParamTable(
                names=("e", "M", "a", "b"), rows=((0.8, 1.2, 1.0, 3.0), (0.5, 1.0, 0.0, 3.0), (0.99, 2.0, 2.0, 3.0))
            ),
        )

    cases = (
        FormulaTestCase.value(
            params={"e": 0.8, "M": 1.2, "a": 1.0, "b": 3.0}, x=1.6, c=0.0, expected=-0.399658882433204
        ),
        FormulaTestCase.value(
            params={"e": 0.8, "M": 1.2, "a": 1.0, "b": 3.0}, x=1.6, c=0.25, expected=-0.8129658880491483
        ),
        FormulaTestCase.value(
            params={"e": 0.5, "M": 1.0, "a": 0.0, "b": 3.0}, x=0.9, c=0.0, expected=-0.4916634548137417
        ),
        FormulaTestCase.value(
            params={"e": 0.99, "M": 2.0, "a": 2.0, "b": 3.0}, x=2.3, c=0.0, expected=-0.43824816005495326
        ),
        FormulaTestCase.interval_bounds(params={"e": 0.8, "M": 1.2, "a": 1.0, "b": 3.0}, expected=(1.0, 3.0)),
        FormulaTestCase.interval_bounds(params={"e": 0.5, "M": 1.0, "a": 0.0, "b": 3.0}, expected=(0.0, 3.0)),
        FormulaTestCase.interval_bounds(params={"e": 0.99, "M": 2.0, "a": 2.0, "b": 3.0}, expected=(2.0, 3.0)),
    )
