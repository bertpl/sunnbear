"""This module holds the formula that Alefeld, Potra (1992) labels 1 and 4.

A script generates this module from the survey of published test problems: to change the formula, change its source file
in `data/literature_test_problems/sources/` and run `uv run python -m scripts.literature_test_problems.formula_modules
1992_alefeld_potra`; do not edit this file.
"""

from sunnbear._core.functions.core import Formula, FormulaSource, FormulaTestCase, ParamRecipe, ParamTable

# SURVEY_FIELDS_HASH is a hash of this formula's survey fields; the tests recompute it from the
# survey, so that a test fails when the survey changes and this module is not regenerated.
SURVEY_FIELDS_HASH = "de6481503216bcb3"


class AlefeldPotra19921(Formula):
    """This formula evaluates the published function at ``x - (b - a)*c``, where ``[a, b]`` is its interval.

    The source prints 1 function in 2 rows, each with its own parameter values; with each row's values replaced by
    parameters, that function is ``x^3 - a``:

    - 1, with ``a = 1``: ``x^3 - 1``; the formula's interval is ``[0.5, 1.5]``
    - 4, with ``a = -1``: ``x^3 + 1``; the formula's interval is ``[-1.8, 0]``

    The formula's parameter ``a_`` is the source's ``a``, renamed because the formula uses ``a`` for another value.
    """

    number = (1, 2, 3, 1)
    name = "1"
    param_names = ("a_", "a", "b")
    source = FormulaSource(
        reference=(
            "Alefeld, G. E., Potra, F. A. (1992). Some efficient methods for enclosing simple zeros of "
            "nonlinear equations. BIT 32(2), 334–344. https://doi.org/10.1007/bf01994885."
        ),
        location="1, 4",
    )

    @staticmethod
    def parametrized_fun(x: float, c: float, a_: float, a: float, b: float) -> float:
        """Evaluate the published function at ``x - (b - a)*c``, where ``[a, b]`` is the formula's interval."""
        x = x - (b - a) * c
        return x**3 - a_

    def interval_bounds(self, a_: float, a: float, b: float) -> tuple[float, float]:
        """Return the interval of the tuple, its parameters ``a`` and ``b``."""
        return (a, b)

    def recipes(self) -> tuple[ParamRecipe, ...]:
        """Return the published parameter values."""
        return (ParamTable(names=("a_", "a", "b"), rows=((1.0, 0.5, 1.5), (-1.0, -1.8, 0.0))),)

    cases = (
        FormulaTestCase.value(params={"a_": 1.0, "a": 0.5, "b": 1.5}, x=0.8, c=0.0, expected=-0.48799999999999993),
        FormulaTestCase.value(params={"a_": 1.0, "a": 0.5, "b": 1.5}, x=0.8, c=0.25, expected=-0.833625),
        FormulaTestCase.value(params={"a_": -1.0, "a": -1.8, "b": 0.0}, x=-1.26, c=0.0, expected=-1.000376),
        FormulaTestCase.interval_bounds(params={"a_": 1.0, "a": 0.5, "b": 1.5}, expected=(0.5, 1.5)),
        FormulaTestCase.interval_bounds(params={"a_": -1.0, "a": -1.8, "b": 0.0}, expected=(-1.8, 0.0)),
    )
