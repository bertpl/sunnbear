"""This module holds the formula that Alefeld, Potra, Shi (1993) labels T5.1-3.

A script generates this module from the survey of published test problems: to change the formula, change its source file
in `data/literature_test_problems/sources/` and run `uv run python -m scripts.literature_test_problems.formula_modules
1993_alefeld_potra_shi`; do not edit this file.
"""

import math

from sunnbear._core.functions.core import Formula, FormulaSource, FormulaTestCase, ParamRecipe, ParamTable

# SURVEY_FIELDS_HASH is a hash of this formula's survey fields; the tests recompute it from the
# survey, so that a test fails when the survey changes and this module is not regenerated.
SURVEY_FIELDS_HASH = "c99ad3fdf6f6c7a2"


class AlefeldPotraShi1993T513(Formula):
    """This formula evaluates the published function at ``x - (b - a)*c``, where ``[a, b]`` is its interval.

    The survey writes the source's function as ``a*x*exp(b*x)``, with the parameters `a = -40, b = -1`; `a = -100, b =
    -2`; `a = -200, b = -3`; the formula's interval is ``[-9, 31]``.

    Here `a` and `b` are the function's parameters, not the interval's endpoints.
    """

    number = (1, 2, 4, 3)
    name = "T5.1-3"
    param_names = ("a", "b")
    source = FormulaSource(
        reference=(
            "Alefeld, G., Potra, F. A., Shi, Y. (1993). On enclosing simple roots of nonlinear "
            "equations. Mathematics of Computation 61(204), 733–744. "
            "https://doi.org/10.1090/s0025-5718-1993-1192965-2."
        ),
        location="T5.1-3",
    )

    @staticmethod
    def parametrized_fun(x: float, c: float, a: float, b: float) -> float:
        """Evaluate the published function at ``x - (b - a)*c``, where ``[a, b]`` is the formula's interval."""
        x = x - 40.0 * c
        return a * x * math.exp(b * x)

    def interval_bounds(self, a: float, b: float) -> tuple[float, float]:
        """Return the formula's interval."""
        return (-9.0, 31.0)

    def recipes(self) -> tuple[ParamRecipe, ...]:
        """Return the published parameter values."""
        return (ParamTable(names=("a", "b"), rows=((-40.0, -1.0), (-100.0, -2.0), (-200.0, -3.0))),)

    cases = (
        FormulaTestCase.value(params={"a": -40.0, "b": -1.0}, x=3.0, c=0.0, expected=-5.974448204143673),
        FormulaTestCase.value(params={"a": -40.0, "b": -1.0}, x=3.0, c=0.25, expected=307057.2843599684),
        FormulaTestCase.value(params={"a": -100.0, "b": -2.0}, x=3.0, c=0.0, expected=-0.7436256529999076),
        FormulaTestCase.value(params={"a": -200.0, "b": -3.0}, x=3.0, c=0.0, expected=-0.07404588245200773),
        FormulaTestCase.interval_bounds(params={"a": -40.0, "b": -1.0}, expected=(-9.0, 31.0)),
    )
